// 验证「提取后续词组 / 提取前置词组」的边界与分段行为。
// 与旧版不同：直接动态导入 js/查找弹窗.js 的导出（提取后续词组自文本 / 提取前置词组自文本），
// 测的是真实发布代码，不再用字符串复制源码重建（那会随实现演进而静默漂移）。
// 查找弹窗的依赖闭包在模块求值期只触 document.querySelector 与 document.baseURI，
// 用最小 stub 即可在 Node 下加载。

const 空元素 = new Proxy(
  {},
  {
    get(目标, 键) {
      if (键 === 'getContext') {
        return function 获取画布上下文() {
          return {};
        };
      }
      if (键 === 'append') {
        return function 追加元素() {};
      }
      return 空元素;
    },
  },
);

globalThis.document = {
  baseURI: 'http://127.0.0.1/',
  querySelector() {
    return 空元素;
  },
  createElement() {
    return 空元素;
  },
};
globalThis.localStorage = {
  getItem() {
    return null;
  },
};

const { 提取后续词组自文本, 提取前置词组自文本 } = await import(
  '../js/查找弹窗.js'
);

const 场景 = [];
function 检查(name, 文本, 偏移, 前缀, 期望前, 期望后) {
  const 后 = 提取后续词组自文本(文本, 偏移, 前缀.length);
  const 前 = 提取前置词组自文本(文本, 偏移);
  const ok后 = 后 === 期望后;
  const ok前 = 前 === 期望前;
  场景.push({
    name,
    pass: ok前 && ok后,
    detail: `前=[${期望前}] 得[${前}]${ok前 ? '' : ' ✗'} | 后=[${期望后}] 得[${后}]${ok后 ? '' : ' ✗'}`,
  });
}

// 1. 常规:前面接词 + 关键词 + 后面接词
检查('常规两侧', '他向阁老请安去了', 2, '阁老', '向', '阁老请');
// 2. 文首命中(无前置上下文)
检查('文首', '阁老已经到了', 0, '阁老', '', '阁老已经');
// 3. 文末命中(无后续内容;分段器把前面的词整词返回)
检查('文末', '他去拜见阁老', 4, '阁老', '拜见', '阁老');
// 4. 标点紧邻(标点不是词,后面接不出词组 → 只返回关键词本身,由调用方过滤)
检查('标点分隔', '大人,阁老,请留步', 3, '阁老', '', '阁老');
// 5. 关键词开头即整句结尾且前面是冒号
检查('冒号前', '众人齐呼:"阁老"', 6, '阁老', '', '阁老');
// 6. 长前置截断(前置窗口恰好切在 64 字边界,顿号保证分段确定)
const 长前文 = '甲,'.repeat(40) + '见阁老,去了';
const 长前偏移 = '甲,'.repeat(40).length + 1;
检查('长前置截断', 长前文, 长前偏移, '阁老', '见', '阁老');
// 7. 长后文截断
检查('长后文截断', '阁老去' + '乙'.repeat(80), 0, '阁老', '', '阁老去');

let 失败数 = 0;
for (const s of 场景) {
  if (!s.pass) 失败数 += 1;
  console.log(`${s.pass ? 'PASS' : 'FAIL'} ${s.name}: ${s.detail}`);
}
console.log(失败数 ? `\n${失败数} 个场景失败` : '\n全部通过');
process.exit(失败数 ? 1 : 0);
