检查('长前置截断', 长前文, 长前偏移, '阁老', '见', '阁老,');
// 7. 长后文截断
检查('长后文截断', '阁老去' + '乙'.repeat(80), 0, '阁老', '', '阁老去');

function 检查扩展(name, 全文, 锚点列表, 已有接续, 向后, 期望) {
  const 得 = 扩展唯一汉字接续(全文, 锚点列表, 已有接续, 向后);
  场景.push({
    name,
    pass: 得 === 期望,
    detail: `期望[${期望}] 得[${得}]${得 === 期望 ? '' : ' ✗'}`,
  });
}

function 前置高频(全文, 关键词) {
  const 分组 = new Map();
  let 搜索 = 0;
  while (搜索 <= 全文.length - 关键词.length) {
    const 偏移 = 全文.indexOf(关键词, 搜索);
    if (偏移 < 0) break;
    const 前置 = 提取前置词组自文本(全文, 偏移);
    const 键 = 邻接字(前置, false);
    if (前置 && 键) {
      // 锚点 = 词组实际终点（跨过标点时不粘连关键词）
      const 实际 = 全文.lastIndexOf(前置, 偏移 - 前置.length);
      const 锚点 = 实际 >= 0 ? 实际 + 前置.length : 偏移;
      const 列表 = 分组.get(键);
      if (列表) 列表.push(锚点);
      else 分组.set(键, [锚点]);
    }
    搜索 = 偏移 + 关键词.length;
  }
  return [...分组]
    .filter(function 过滤单次([, 锚点列表]) {
      return 锚点列表.length > 1;
    })
    .map(function 扩展项([词组, 锚点列表]) {
      return [扩展唯一汉字接续(全文, 锚点列表, 词组, false), 锚点列表.length];
    });
}

function 后续高频(全文, 关键词) {
  const 分组 = new Map();
  let 搜索 = 0;
  while (搜索 <= 全文.length - 关键词.length) {
    const 偏移 = 全文.indexOf(关键词, 搜索);
    if (偏移 < 0) break;
    const 后续 = 提取后续词组自文本(全文, 偏移, 关键词.length);
    const 接续 = 后续.slice(关键词.length);
    const 键 = 邻接字(接续, true);
    if (键) {
      // 锚点 = 接续实际起点（跨过标点时不粘连关键词）
      const 实际 = 全文.indexOf(接续, 偏移 + 关键词.length);
      const 锚点 = 实际 >= 0 ? 实际 : 偏移 + 关键词.length;
      const 列表 = 分组.get(键);
      if (列表) 列表.push(锚点);
      else 分组.set(键, [锚点]);
    }
    搜索 = 偏移 + 关键词.length;
  }
  return [...分组]
    .filter(function 过滤单次([, 锚点列表]) {
      return 锚点列表.length > 1;
    })
    .map(function 扩展项([词组, 锚点列表]) {
      return [扩展唯一汉字接续(全文, 锚点列表, 词组, true), 锚点列表.length];
    });
}

