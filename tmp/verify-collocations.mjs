// 4. 标点紧邻(标点按自身归类:前取紧贴的标点、后同理;不再跨标点找词)
检查('标点分隔', '大人,阁老,请留步', 3, '阁老', ',', '阁老,');
// 5. 关键词前是引号(引号本身即组;关键词后紧跟闭引号,归 " 组)
检查('冒号前', '众人齐呼:"阁老"', 6, '阁老', '"', '阁老"');
// 6. 长前置截断(前置窗口恰好切在 64 字边界;见 紧贴关键词归 见,逗号在关键词后归 , 组)
