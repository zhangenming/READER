// 14. 提取后再扩展：搜太监时前面接应是秉笔，而不是笔
{
  const 全文 =
    '一个太监来了。秉笔太监走了。又见秉笔太监。当值太监尚在。当值太监已走。';
  const 结果 = 前置高频(全文, '太监');
  const 条目 = Object.fromEntries(结果);
  const 无笔 = !条目.笔;
  const 有秉笔 = 条目.秉笔 === 2;
  const 有一个 = 条目.一个 === undefined; // 只出现一次，不展示
  const 有当值 = 条目.当值 === 2;
  场景.push({
    name: '搜太监前面接显示秉笔',
    pass: 无笔 && 有秉笔 && 有一个 && 有当值,
    detail: `结果=${JSON.stringify(条目)} 无笔=${无笔} 秉笔=${条目.秉笔} 当值=${条目.当值}`,
  });
}
// 15. 线上 bug 复现：搜「和阗」时 玉杵/玉镂空/玉圆球/玉佩 被分段器切成
