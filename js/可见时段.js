import { 创建时段存储, 未分书键 } from './滚动时段.js';

// 页面可见时间段：记录「几点到几点开着页面且载入了书」，开关会话的唯一入口是
// 前台停留.js 的 更新前台停留计时()，与滚动时段用同一个工厂、同一套无损合并规则，
// 两边都按书拆开，形状完全对称。
//
// 「可见」包含正在滚动的部分（滚动必然发生在页面开着的时候），所以它不是给玩家看的
// 那一列：展示层的三列是由它派生的 ——
//   总计 = 可见 ∪ 滚动（就是轴上那条铺开的浅灰带）
//   滚动 = 滚动段（压在带上的深色块）
//   激活 = 可见 − 滚动（带子露出来的部分：开着页面但没在滚，手动读、发呆、开弹窗都算）
// 三列同账：激活 + 滚动 = 总计，谁也不含谁。
//
// 旧版这份账叫「每日激活时段」（那时激活＝可见，含滚动），读回来仍然用，只是现在
// 语义上它是「可见段」；持久化新键名 每日可见时段，旧键名做回落。
// 依赖：滚动时段.js（工厂），不 import 持久化/前台停留，避免成环。
const 可见时段存储 = 创建时段存储({
  读取持久化: (数据) =>
    数据?.前台停留统计?.每日可见时段 ??
    数据?.前台停留统计?.每日激活时段,
  名称: '页面可见时段',
});

export const 每日可见时段 = 可见时段存储.每日时段;
export const 开始可见时段 = 可见时段存储.开始;
export const 结束可见时段 = 可见时段存储.结束;
export const 记录可见时段 = 可见时段存储.记录;
export const 获取当日可见时段 = 可见时段存储.获取当日;
export const 获取当日按书可见时段 = 可见时段存储.获取当日按书;
export const 可见当日总秒 = 可见时段存储.当日总秒;
export const 本书可见当日总秒 = 可见时段存储.本书当日总秒;
export const 载入可见时段统计 = 可见时段存储.载入;
export const 可见时段统计快照 = 可见时段存储.快照;
export const 获取进行中可见时段 = 可见时段存储.获取进行中;
export { 未分书键 };
