import { 元素 } from './状态.js';
import { 格式化次数, 格式化倍数, 格式化万分率 } from './万分率.js';
import { 取知乎序号, 取知乎万分率 } from './知乎字频.js';

// 字频差异榜：词频对照右侧的独立模块，三列各 30 行，一次渲染完，
// 不进 虚拟列表、也不跟主表共享滚动容器（主表滚多少都与它无关）。
// 顶部另有一条 汇总偏度：把整本书压成「语域偏离 / 主题偏离 / 与知乎重合」三个数，
// 榜单是局部证据、汇总是全局结论，两者共用同一批 对数差 与同一个 格式化倍数。
//
// 差异口径 = 本书万分之 ÷ 知乎万分之 的倍数（按 |log2| 排序）。
// 不用绝对差是因为：绝对差的最大端永远是「的了是一」这些高频虚词，
// 最小端永远是两边都几乎不出现的生僻字，两头都没有信息量。
// 本书出现过的每个字都入榜，不做次数门槛；但知乎那一侧必须有数：
// 计 0 次或压根未收录的字没有分母，属于「没有数据」而不是「差异极大」，
// 折算成 1 次会把它们顶到榜首（×6,117 那种），所以直接排除并在说明里报数量。

const 榜长 = 30;

function 计算差异行(分析) {
  const 行列表 = [];
  let 无现代数据字数 = 0;
  for (const 项 of 分析.列表[1]) {
    const 现代显示 = 取知乎万分率(项.文本); // 未收录为 undefined，显示要与主表一致
    const 现代 = 现代显示 ?? 0;
    if (现代 <= 0) {
      无现代数据字数 += 1;
      continue;
    }
    const 本书万分之 = (项.数量 / 分析.汉字总数) * 10000;
    const 比值 = 本书万分之 / 现代;
    行列表.push({
      文本: 项.文本,
      现代显示,
      现代,
      本书万分之,
      比值,
      对数差: Math.abs(Math.log2(比值)),
      本书次数: 项.数量,
      现代名次: 取知乎序号(项.文本),
    });
  }
  return { 行列表, 无现代数据字数 };
}

// 汇总偏度：把榜单背后那一列「倍数」压成全书级别的数。
//
// 通用形式 = 2 ^ ( Σ 本书次数 × |log₂ 倍数| ÷ 计入字数 )
//   按次数加权、走对数两个约束都省不掉：
//   * 直接对「倍数」取算术平均会被长尾炸掉（金瓶梅 27、成吉思汗 68 全是
//     ×4000 那档生僻字顶起来的），而且 ×2 与 ÷2 在它不等权（平均成 1.25
//     而不是 1，偏本书和偏知乎两个方向互相污染）；
//   * 按字种等权（每个字一票）随书的长度单调上涨（金瓶梅 5 千字 3.97 →
//     全书 4.63），量的是「字表攒了多长」而不是这本书的用语风格；
//   * 只有按次数加权在 2 万字后就稳住（3.16 → 3.35，残下的漂移是真差异），
//     不同长度的书可以直接横向比。
//
// 关键是这个量要**拆成两段报**，合起来一个数会骗人。前 100 常用字（的、一、
// 是、不、我……知乎表里几乎全是虚词）单独算「语域偏离」，其余 7,322 字算
// 「主题偏离」——两者是完全不同的东西：
//   书        语域   主题     一句话
//   债务危机   ×1.69  ×4.31   中文是标准当代书面语，只是满篇债贷币储胀
//   笑傲江湖   ×1.58  ×3.94   的÷2.4、之×3.3 的半文言 + 令狐冲人名
//   金瓶梅     ×1.91  ×4.61   两段都偏，才是真「不像现代人写的」
//   成吉思汗   ×2.69  ×9.61   音译专名把常用字分布整个换掉了
// 合成一个数的话 债务危机（×3.22）会排在 笑傲江湖（×2.77）前面，读起来像
// 「这本财经书比金庸更不现代」——那是错的：它的语域段和 骆驼祥子（×1.68）
// 一个水平。主题词表的偏斜和语言时代的偏斜必须分账看。
// 阈值取名次而不是万分之数值，是因为名次直接对应「前 100 常用字」这个说法，
// 换语料表也不用重算门限；前 100 大约覆盖全书 31%~49% 篇幅，随书浮动。
const 语域段名次 = 100;

function 汇总偏度(行列表, 分析) {
  let 语域对数差和 = 0;
  let 语域字数 = 0;
  let 主题对数差和 = 0;
  let 主题字数 = 0;
  for (const 行 of 行列表) {
    const 加重对数差 = 行.本书次数 * 行.对数差;
    if (行.现代名次 !== undefined && 行.现代名次 <= 语域段名次) {
      语域对数差和 += 加重对数差;
      语域字数 += 行.本书次数;
    } else {
      主题对数差和 += 加重对数差;
      主题字数 += 行.本书次数;
    }
  }
  let 重合万分之 = 0;
  for (const 项 of 分析.列表[1]) {
    重合万分之 += Math.min(
      (项.数量 / 分析.汉字总数) * 10000,
      取知乎万分率(项.文本) ?? 0,
    );
  }
  const 计入字数 = 语域字数 + 主题字数;
  // 某段一个字都没有时返回 undefined，交给 格式化倍数 显示「—」，不写 ×NaN
  const 求偏离 = (和, 字数) =>
    字数 > 0 ? 2 ** (和 / 字数) : undefined;
  return {
    语域偏离: 求偏离(语域对数差和, 语域字数),
    主题偏离: 求偏离(主题对数差和, 主题字数),
    总偏离: 求偏离(语域对数差和 + 主题对数差和, 计入字数),
    语域篇幅: 分析.汉字总数 > 0 ? 语域字数 / 分析.汉字总数 : 0,
    // 重合度 = Σ min(本书万分之, 知乎万分之) ÷ 10000，即 1 - 全变差距离。
    // 同一信息的有界版本，永远落在 0~100%，天然抗离群值。两侧都是真分布
    // （表合计 10000、本书合计 10000），本书没用过的字 min 为 0、表里没有的
    // 字也是 0，所以只需遍历本书字种，不用补集也不用重归一。
    重合度: 重合万分之 / 10000,
    // 知乎侧没有分母的字占全书多少篇幅——偏离没把它们算进去，
    // 这个数负责说明「漏掉了多少」，不让汇总数看着像覆盖了全文。
    计入篇幅: 分析.汉字总数 > 0 ? 计入字数 / 分析.汉字总数 : 0,
  };
}

/** 篇幅占比：真为 0 时返回空串（说明里不写「0.00%」这种杂讯），不足 0.01% 单独标出 */
function 格式化篇幅(分数) {
  if (!(分数 > 0)) {
    return '';
  }
  const 百分比 = 分数 * 100;
  return 百分比 < 0.01 ? '<0.01%' : `${百分比.toFixed(2)}%`;
}

function 排序取榜(行列表, 取最大) {
  return 行列表.slice().sort(function 比较差异(左, 右) {
    const 差 = 取最大 ? 右.对数差 - 左.对数差 : 左.对数差 - 右.对数差;
    if (差 !== 0) {
      return 差;
    }
    // 差异相同（如互为倒数、或都是知乎未收录）时按常用度排，保证结果稳定可复现
    return (
      右.现代 - 左.现代 ||
      右.本书次数 - 左.本书次数 ||
      左.文本.localeCompare(右.文本, 'zh-CN')
    );
  });
}

function 填列(表体, 行列表) {
  const 片段 = document.createDocumentFragment();
  for (const 行 of 行列表) {
    const 节点 = document.createElement('tr');
    const 字格 = document.createElement('td');
    const 现代格 = document.createElement('td');
    const 本书格 = document.createElement('td');
    const 倍数格 = document.createElement('td');
    字格.textContent = 行.文本;
    现代格.textContent = 格式化万分率(行.现代显示);
    // 本书格：万分之后面跟上真实次数。万分之是相对量，2.8 万字的书和 50 万字的书
    // 同一个数完全不是一回事；括号里的个数让人一眼看出这个差异站在多少字上。
    本书格.textContent = 格式化万分率(行.本书万分之);
    const 个数 = document.createElement('span');
    个数.className = '本书个数';
    个数.textContent = ` (${行.本书次数.toLocaleString('zh-CN')})`;
    本书格.append(个数);
    倍数格.textContent = 格式化倍数(行.比值);
    倍数格.classList.add(行.比值 >= 1 ? '字频偏本书' : '字频偏知乎');
    节点.title =
      `知乎万分之 ${行.现代显示 === undefined ? '未收录' : 行.现代.toFixed(6)}` +
      `（${行.现代名次 === undefined ? '现代字频表未收录' : `第 ${行.现代名次} 名`}）· ` +
      `本书万分之 ${行.本书万分之.toFixed(4)} · 出现 ${行.本书次数.toLocaleString('zh-CN')} 次`;
    节点.append(字格, 现代格, 本书格, 倍数格);
    片段.append(节点);
  }
  表体.replaceChildren(片段);
}

export function 渲染字频差异榜(分析) {
  const { 行列表, 无现代数据字数 } = 计算差异行(分析);
  // 「差异最大」按方向拆成两列：× 是本书远比现代常用，÷ 是本书远比现代少用。
  // 混在一列里时两端会互相挤掉，看不出这本书到底是回避还是偏爱某类字。
  const 偏多 = 排序取榜(行列表.filter((行) => 行.比值 > 1), true).slice(0, 榜长);
  const 偏少 = 排序取榜(行列表.filter((行) => 行.比值 < 1), true).slice(0, 榜长);
  const 最小 = 排序取榜(行列表, false).slice(0, 榜长);
  填列(元素.字频差异偏多列表, 偏多);
  填列(元素.字频差异偏少列表, 偏少);
  填列(元素.字频差异最小列表, 最小);
  const 汇总 = 汇总偏度(行列表, 分析);
  // 偏离全部复用 格式化倍数：它和右侧那一列是同一个量纲，显示口径也必须一致，
  // 否则榜单里的 ×1.8 和顶上的 1.8 看着像两回事。
  元素.字频差异语域偏离.textContent = 格式化倍数(汇总.语域偏离);
  元素.字频差异主题偏离.textContent = 格式化倍数(汇总.主题偏离);
  元素.字频差异重合度.textContent = `${(汇总.重合度 * 100).toFixed(1)}%`;
  const 未计入篇幅 = 格式化篇幅(1 - 汇总.计入篇幅);
  元素.字频差异汇总.title =
    `语域偏离：只取知乎表前 ${语域段名次} 常用字（的、一、是、不、我……几乎全是虚词，` +
    `本书里约 ${(汇总.语域篇幅 * 100).toFixed(0)}% 的篇幅落在这段），` +
    `|log₂ 倍数| 的字数加权几何平均。量的是这本书的中文离当代白话有多远。\n` +
    `主题偏离：其余字同一算法。量的是题材用字有多专（债贷币储胀、令狐冲剑岳）。\n` +
    `两段必须分开看：合起来的总偏离是 ×${(汇总.总偏离 ?? 1).toFixed(2)}，` +
    `单看它会把「主题很专」误读成「语言不现代」——《债务危机》总 ×3.22 高于《笑傲江湖》` +
    `×2.77，但它的语域只有 ×1.69（和《骆驼祥子》×1.68 一个水平），高全在主题 ×4.31。\n` +
    `重合度：本书字频分布与知乎字频分布重合的部分占多少（每字两侧取小再相加），` +
    `100% 表示用字习惯完全一致。\n` +
    `知乎计 0 次或未收录的字没有分母，不入偏离` +
    (未计入篇幅 ? `（它们占全书 ${未计入篇幅} 篇幅）` : '') +
    `；重合度按 min(p, 0) 计，不受影响。`;
  元素.字频差异说明.textContent =
    `本书万分之 ÷ 知乎万分之 · 按 |log₂ 倍数| 分向排成三列 · ` +
    `本书列括号内为出现次数 · ` +
    `本书 ${分析.去重汉字数.toLocaleString('zh-CN')} 字中 ` +
    `${行列表.length.toLocaleString('zh-CN')} 字入榜，知乎计 0 次或未收录的 ` +
    `${无现代数据字数.toLocaleString('zh-CN')} 字无数据、不入榜` +
    (未计入篇幅 ? `（占全书 ${未计入篇幅} 篇幅）` : '');
  元素.字频差异偏多标题.textContent = `偏本书 ×${偏多.length}`;
  元素.字频差异偏少标题.textContent = `偏知乎 ÷${偏少.length}`;
  元素.字频差异最小标题.textContent = `差异最小 ${最小.length}`;
}
