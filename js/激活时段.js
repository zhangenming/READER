import { 激活时段合并间隙秒 } from './常量.js';
import { 创建时段存储 } from './滚动时段.js';

// 页面激活时间段：把「前台停留」从"累计了多少分钟"升级成"几点到几点开着页面"，
// 与 前台停留.js 同一口径 —— 有书载入且 document.visibilityState === 'visible' 才算激活，
// 手动阅读、自动滚动、打开弹窗都包含在内，切标签页/最小化即结束一段。
// 开关会话的唯一入口是 前台停留.js 的 更新前台停留计时()，所以时长与时段天然同步，不会各记一套。
//
// 时段机制（跨午夜切分、合并、上限、按龄裁剪、快照含进行中段）复用 滚动时段.js 的工厂；
// 只有合并间隙不同：切走再回来是真实离开，只抹 10 秒内的抖动，不像滚动那样并掉 60 秒。
//
// 数据不按书拆分（与滚动时段一样，全部书籍合成一条作息轴），只以本地日期为键。
// 依赖：常量.js 与 滚动时段.js（叶子层），不 import 持久化/前台停留，避免成环。
const 激活时段存储 = 创建时段存储({
  读取持久化: (数据) => 数据?.前台停留统计?.每日激活时段,
  合并间隙秒: 激活时段合并间隙秒,
  名称: '页面激活时段',
});

export const 每日激活时段 = 激活时段存储.每日时段;
export const 开始激活时段 = 激活时段存储.开始;
export const 结束激活时段 = 激活时段存储.结束;
export const 获取当日激活时段 = 激活时段存储.获取当日;
export const 获取进行中激活时段 = 激活时段存储.获取进行中起点;
export const 载入激活时段统计 = 激活时段存储.载入;
export const 激活时段统计快照 = 激活时段存储.快照;
