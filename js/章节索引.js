import { 按需让出主线程 } from './调度.js';

const 章号 =
  '[0-9零〇○一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,16}';
const 编号标题 = new RegExp(
  `^第\\s*${章号}\\s*(章|回|卷|部分|部|节|集)(?:$|[\\s:：、.．—-].*)`,
);
const 卷标题 = new RegExp(`^卷\\s*${章号}(?:$|[\\s:：、.．—-].*)`);
const 特殊标题 =
  /^(序章|楔子|序言|前言|绪言|引言|序幕|尾声|终章|后记|附录|致谢)(?:$|[\s:：、—-].*)/u;
const 英文章标题 = /^chapter\s+(?:\d{1,6}|[ivxlcdm]+)(?:$|[\s:：.—-].*)/iu;
const 目录标题 = /^(?:目\s*录|contents|table of contents)$/iu;

function 识别标题(标题) {
  const 匹配 = 标题.match(编号标题);
  if (匹配) {
    return ['卷', '部', '部分'].includes(匹配[1]) ? '分卷' : '章节';
  }
  if (卷标题.test(标题)) return '分卷';
  if (特殊标题.test(标题)) return '序跋';
  if (英文章标题.test(标题)) return '章节';
  return null;
}

// 只扫描规范化后的原始行，不能把阅读器自动插入的句子换行当作标题边界。
export async function 创建章节索引(文本, 任务仍然有效 = () => true) {
  const 章节列表 = [];
  const 双语候选 = [];
  let 目录块 = null;
  let 英文候选 = null;
  let 上行为空 = true;
  let 时间片开始 = performance.now();
  let 下次让出位置 = 4096;

  for (let 起点 = 0; 起点 < 文本.length; ) {
    const 换行 = 文本.indexOf('\n', 起点);
    const 终点 = 换行 < 0 ? 文本.length : 换行;
    const 原行 = 终点 - 起点 <= 120 ? 文本.slice(起点, 终点).trim() : null;
    const 标题 = 原行?.normalize('NFKC').replace(/\s+/gu, ' ') ?? null;
    const 类型 = 标题 ? 识别标题(标题) : null;

    if (标题 !== '') {
      if (标题 && 目录标题.test(标题)) {
        目录块 = { 标题集合: new Set(), 分卷: '', 待确认: [] };
        英文候选 = null;
      } else {
        if (目录块 && !类型 && (标题 === null || /[。！？!?；;]/u.test(标题))) {
          // 标题重现后仍需正文确认，不能把目录里不同卷的重号当作正文开始。
          章节列表.push(...目录块.待确认);
          目录块 = null;
        }
        if (类型) {
          const 章节 = { 标题: 原行, 偏移: 起点, 类型 };
          if (目录块) {
            // 目录与正文标题常常只差一个空格（正文里章题是两行：“第一章\n《…》”），
            // 配对键去掉空白，否则整本书的章节都确认不上。
            const 标题键 = 标题
              .replace(/(?:\s*[…·.．]{2,}\s*|\s+)\d+\s*$/u, '')
              .replace(/\s+/gu, '');
            if (类型 === '分卷') 目录块.分卷 = 标题键;
            const 键 = `${目录块.分卷}\n${标题键}`;
            if (目录块.标题集合.has(键)) {
              目录块.待确认.push(章节);
            } else {
              目录块.待确认 = [];
            }
            目录块.标题集合.add(键);
          } else {
            章节列表.push(章节);
          }
          英文候选 = null;
        } else if (!目录块) {
          if (
            英文候选 &&
            标题 &&
            标题.length <= 60 &&
            /^[\p{Script=Han}]/u.test(标题) &&
            !/[。！？!?；;]/u.test(标题)
          ) {
            双语候选.push({
              标题: `${英文候选.标题} · ${原行}`,
              偏移: 英文候选.偏移,
              类型: '章节',
              章号: 英文候选.章号,
            });
          }
          const 英文匹配 =
            上行为空 &&
            标题?.match(/^(\d{1,4})\s+([A-Za-z][A-Za-z\s'’“”",:—-]+)$/u);
          英文候选 = 英文匹配
            ? { 标题: 原行, 偏移: 起点, 章号: Number(英文匹配[1]) }
            : null;
        }
      }
    }
    上行为空 = 标题 === '';
    起点 = 终点 + 1;
    if (起点 >= 下次让出位置) {
      时间片开始 = await 按需让出主线程(时间片开始);
      if (!任务仍然有效()) return null;
      下次让出位置 = 起点 + 4096;
    }
  }

  // 裸数字标题仅在存在完整、连续的中英配对序列时启用，避免收录正文问卷或清单。
  if (
    双语候选.length >= 3 &&
    双语候选.every((项, idx) => 项.章号 === idx + 1)
  ) {
    for (const { 章号: _, ...章节 } of 双语候选) 章节列表.push(章节);
    章节列表.sort((左, 右) => 左.偏移 - 右.偏移);
  }
  return 任务仍然有效() ? 章节列表 : null;
}

/* 给定文本偏移读到了某章的几成（钳在 0~1）。单独拆出来是因为「在哪一章」按视口
   顶边算、「这一章看过几成」按视口底边算，两个参考点落在不同章上时不能各查各的。 */
export function 章节内进度(章节列表, 索引, 偏移, 文本长度) {
  const 章节 = 章节列表[索引];
  if (!章节) return 0;
  const 终点 = 章节列表[索引 + 1]?.偏移 ?? 文本长度;
  return Math.min(
    1,
    Math.max(0, (偏移 - 章节.偏移) / Math.max(1, 终点 - 章节.偏移)),
  );
}

export function 计算章节进度(章节列表, 阅读偏移, 文本长度) {
  let 左 = 0;
  let 右 = 章节列表.length;
  while (左 < 右) {
    const 中 = (左 + 右) >>> 1;
    if (章节列表[中].偏移 <= 阅读偏移) 左 = 中 + 1;
    else 右 = 中;
  }
  const 索引 = 左 - 1;
  if (索引 < 0) return { 索引: -1, 进度: 0 };
  return { 索引, 进度: 章节内进度(章节列表, 索引, 阅读偏移, 文本长度) };
}
