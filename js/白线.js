import { 元素, 状态 } from './状态.js';

/* ===== 上下两条白线：整行视口的余数槽，纯浮层、不动正文布局 =====
 * 正文滚动容器始终铺满整个视口；两条白线是 body 的 ::before / ::after 固定浮层
 * （见 styles.css，层序 z-index 1：压得住正文行，但被左侧白轴与右下角读数盖住）。
 * 浮层盖掉多少，正文可视高就剩下多少，而 应用整行视口 把「视口高 − 两条白线」正好
 * 收成整数个行高 —— 空格翻页因此每一屏都是整行，首行与末行都不会被切成半截，
 * 上下还对称、不会一边厚一边薄。
 *
 * 为什么是浮层而不是 body 边框：边框会把容器改矮，改一次就触发一次 ResizeObserver
 * → 重排 → 把 scrollTop 重新对齐到行界，白线的动画被这一下顶掉，看上去像没动画；
 * 浮层只改自己的 height，走 CSS 过渡，正文一动不动。
 *
 * 两个变量 --顶部白线高 / --底部白线高 是**布局量**：正文层 .可见内容 的 top、
 * 画布高、翻页步长、右下角读数的底边都读它，只在窗口高/字号/行距变了时重算。
 * 「收紧到 1px」走 body.白线收紧 的 CSS 覆盖，只改浮层绘制高度，不碰这两个量 ——
 * 于是收放白线时正文、量程、左侧指示条全都不动（见 设置白线收紧）。
 *
 * 行界仍然落在 scrollTop = n × 行高 上：正文层整体下移一条顶线高、画布高多算一条
 * 底线高（见 styles.css 与 排版引擎.js 设置画布高度），于是
 * 「滚动量程 = scrollHeight − clientHeight」这条所有调用点都在用的式子不用改。
 *
 * 左侧那条白轴/关键词刻度/进度读数**故意不读这两个变量**：它按整窗高定位、
 * 用 clientHeight 换算，白线怎么收放都不动它一根像素（用户明确要求）。
 */

export const 最小白线高 = 1; // px；上下各留 1px，与正文配对成画框

// 两条白线的布局量（px）。CSS 变量与这里同步；读这里而不读 getComputedStyle：
// 过渡中计算样式是中间态，而布局与翻页要的是目标值。
let 当前 = { 顶: 最小白线高, 底: 最小白线高 };
let 收紧中 = false;

function 写入(顶, 底) {
  当前 = { 顶, 底 };
  document.documentElement.style.setProperty('--顶部白线高', `${顶}px`);
  document.documentElement.style.setProperty('--底部白线高', `${底}px`);
}

export function 白线高() {
  return 当前;
}

// 正文可视高 = 容器高 − 两条白线。凡「一屏」（翻页步长、快翻距离、密度前瞻窗口）
// 都用它；用容器高会多算白线那几十像素：翻页会跳过头，末行会整行压在白条下面。
// 容器高可由调用方传入：滚动路径上 更新滚动块位置 已经量过一次，别再读一遍
// （见 tests/chapter-integration.test.mjs 的「supplied geometry 不许再读 DOM」）。
export function 正文可视高(容器高度 = 元素.滚动容器.clientHeight) {
  return Math.max(0, 容器高度 - 当前.顶 - 当前.底);
}

let 上次日志 = '';

// 按行高把两条白线排成整行视口：余数对半分，各取整像素。
// 取整是因为 Chrome 会把盒尺寸按设备像素量化，写 11.5px 在非整数 DPR 下被压成
// 11px，两条一起缩就凭空多出 1px 残行；多出的那一像素给底线（末行下面多留一点），
// 上下最多相差 1px。计算只依赖容器高与行高、不依赖自身结果 → 幂等，不来回抖。
export function 应用整行视口(行高 = 状态.行高) {
  const 容器高 = 元素.滚动容器.clientHeight;
  if (!(行高 > 0) || 容器高 <= 0) {
    return 0; // 桩环境/未显示：量不到视口就不动白线
  }
  const 整行数 = Math.floor((容器高 - 2 * 最小白线高) / 行高); // 上下各至少留 1px
  if (整行数 < 1) {
    写入(最小白线高, 最小白线高);
    return 0;
  }
  const 余量 = 容器高 - 整行数 * 行高;
  const 顶 = Math.max(最小白线高, Math.floor(余量 / 2));
  写入(顶, Math.max(最小白线高, Math.round(余量 - 顶)));
  const 日志 = `${整行数}|${行高}|${当前.顶}/${当前.底}`;
  if (上次日志 !== 日志) {
    上次日志 = 日志;
    console.info('[阅读器] 白线已按整行视口均分', {
      行高,
      整行数,
      顶部白线高: 当前.顶,
      底部白线高: 当前.底,
    });
  }
  return 整行数;
}

// 常态下两条白线收在 1px：整行视口是为「一屏一屏翻」服务的，只有那一段时间厚白边才
// 有用；首屏、连续滚动（自动滚动与手动滚轮）本来都停在半行上，厚白线纯属白占视野。
// 收紧由 设置白线收紧 一个开关统管，挂在 body.白线收紧 这个**纯绘制**类上：
// 只改浮层绘制高度（styles.css 的 body.白线收紧::before/::after），
// 不动 --顶部白线高 / --底部白线高 这两个布局量 —— 正文层的位置、画布高、滚动量程、
// 翻页步长、左侧指示条全都不变，所以收放时页面一个字都不跳，只有白条在滑。
// （上一版把 1px 直接写进布局量，正文层的 top 瞬间挪掉 14px、白条却要 240ms 才滑过去，
// 两下分开落位，就是用户看到的「抖动」。）
//
// 谁挂谁卸：挂上是「视口不是整行」的每一刻 —— 开局第一句（app.js 启动）以及连续滚动
// 开始时（js/自动滚动.js 开始自动滚动、app.js 处理手动滚轮的滚轮/触摸）。
// 卸下只有一处：按空格/方向键整屏翻页（js/键盘控制.js 翻页整屏）—— 翻页把视口重新
// 落回整行，均分值的白边才有意义。停止自动滚动（鼠标移动 / 已到文末 / Ctrl+D 关闭）
// 故意**不**解收紧：那之后视口仍停在半行上（用户明确要求：白边只在空格翻页时扩展）。
export function 设置白线收紧(是) {
  if (收紧中 === 是) {
    return;
  }
  收紧中 = 是;
  document.body.classList.toggle('白线收紧', 是);
}

export function 白线收紧中() {
  return 收紧中;
}
