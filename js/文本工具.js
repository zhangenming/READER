import { 字素分段器, 汉字模式, 西文字素模式 } from './常量.js';

let 字素缓存文本 = null;
let 字素缓存结果 = null;

// 全文查找会反复使用同一份字素边界；按字符串值缓存，切换文本时自动失效。
export function 获取文本字素分段(文本) {
  if (文本 !== 字素缓存文本) {
    字素缓存文本 = 文本;
    字素缓存结果 = 字素分段器.segment(文本);
  }
  return 字素缓存结果;
}

export function 清除文本字素分段缓存() {
  字素缓存文本 = null;
  字素缓存结果 = null;
}

export function 是有效文本文件名(文件名) {
  return (
    typeof 文件名 === 'string' &&
    文件名.toLowerCase().endsWith('.txt') &&
    !文件名.includes('/') &&
    !文件名.includes('\\')
  );
}

// 允许子目录相对路径（如「子目录/书.txt」）：txt 目录支持一层分组后，
// 目录读取、载入、持久化都要接受带「/」的名字；但禁止反斜杠、「..」与空段，
// 深度封顶，避免路径跳出 txt 目录。
export function 是有效文本相对路径名(文件名) {
  if (
    typeof 文件名 !== 'string' ||
    !文件名.toLowerCase().endsWith('.txt') ||
    文件名.includes('\\') ||
    文件名.includes('..')
  ) {
    return false;
  }
  const 段 = 文件名.split('/');
  return 段.length <= 4 && 段.every((s) => s.length > 0);
}

// 列表与载入提示只显示书名本身（去掉目录前缀与 .txt），
// 目录归属由分组标题行承担，不重复堆在名字里。
export function 取文本显示名(文件名) {
  const 斜杠位置 = 文件名.lastIndexOf('/');
  const 基名 = 斜杠位置 >= 0 ? 文件名.slice(斜杠位置 + 1) : 文件名;
  return 基名.replace(/\.txt$/i, '');
}

export function 是汉字(字) {
  const 码点 = 字.codePointAt(0);
  return (
    (码点 >= 0x3400 && 码点 <= 0x4dbf) ||
    (码点 >= 0x4e00 && 码点 <= 0x9fff) ||
    (码点 >= 0xf900 && 码点 <= 0xfaff) ||
    (码点 > 0x7f && 汉字模式.test(字))
  );
}

export function 是阅读字符码(码) {
  return (
    (码 >= 0x4e00 && 码 <= 0x9fff) ||
    (码 >= 0x3400 && 码 <= 0x4dbf) ||
    (码 >= 0x61 && 码 <= 0x7a) ||
    (码 >= 0x41 && 码 <= 0x5a) ||
    (码 >= 0x30 && 码 <= 0x39)
  );
}

// 句内停顿标点（含换行 = 段落边界）：作为句段边界，本身不计负担
export function 是句内停顿码(码) {
  return (
    码 === 0x0a || // 换行（物理段落边界）
    (码 >= 0x3000 && 码 <= 0x303f) || // CJK 标点（，。！？；：、…「」《》等）
    (码 >= 0xff00 && 码 <= 0xffef) || // 全角形式（，。！？：；（））
    码 === 0x2026 || // …（省略号）
    (码 >= 0x2014 && 码 <= 0x2015) || // ——（破折号）
    (码 >= 0x2018 && 码 <= 0x201d) || // ‘’ “”（弯引号）
    码 === 0x2c || // ,（西文逗号）
    码 === 0x2e || // .
    码 === 0x3b || // ;
    码 === 0x3a || // :
    码 === 0x21 || // !
    码 === 0x3f // ?
  );
}

export function 是西文字素(字素) {
  return 是西文范围(字素, 0, 字素.length);
}

// 数字（0-9、零~九、〇、两、十百千万亿，含小数点）：整段字素全部为数字字符时才判定为数字，
// 连续西文数字（如 "1984"）会被聚合成一个片段，故需按整段匹配；
// 允许小数点，使 "3.14" 这类小数整体作为数字高亮。
// 千分位分隔符（空格「6 000」、NBSP、逗号「555,000」）本身也是西文，会并进同一片段，
// 故允许数字组之间夹单个分隔符；片段首尾也可能带入空格（「军 200余人」聚成「 200」），一并放行。
const 数字字素模式 =
  /^[ \u00a0]*[0-9〇零一二两三四五六七八九.]+(?:[ ,\u00a0][0-9〇零一二两三四五六七八九.]+)*[ \u00a0]*$/u;
export function 是数字字素(字素) {
  return 数字字素模式.test(字素);
}

export function 是西文范围(文本, 起点, 终点) {
  for (let idx = 起点; idx < 终点; idx += 1) {
    const 码 = 文本.charCodeAt(idx);
    if (
      (码 >= 0x20 && 码 <= 0x7e) ||
      码 === 0xa0 ||
      (码 >= 0xff10 && 码 <= 0xff19) ||
      (码 >= 0xff21 && 码 <= 0xff3a) ||
      (码 >= 0xff41 && 码 <= 0xff5a)
    ) {
      continue;
    }
    if (
      (码 >= 0x4e00 && 码 <= 0x9fff) ||
      (码 >= 0xff01 && 码 <= 0xff5e) ||
      (码 >= 0x3000 && 码 <= 0x3020 && 码 !== 0x3007) ||
      (码 >= 0x2018 && 码 <= 0x201d) ||
      码 === 0x0a ||
      码 === 0x2013 ||
      码 === 0x2014 ||
      码 === 0x2026
    ) {
      return false;
    }
    return 西文字素模式.test(
      起点 === 0 && 终点 === 文本.length ? 文本 : 文本.slice(起点, 终点),
    );
  }
  return 终点 > 起点;
}

export function 是方块字素码(码) {
  return (
    (码 >= 0x4e00 && 码 <= 0x9fff) ||
    (码 >= 0x3400 && 码 <= 0x4dbf) ||
    (码 >= 0xf900 && 码 <= 0xfaff) ||
    (码 >= 0x3000 && 码 <= 0x303f) ||
    (码 >= 0xff01 && 码 <= 0xff5e) ||
    (码 >= 0x2018 && 码 <= 0x201d) ||
    码 === 0x2013 ||
    码 === 0x2014 ||
    码 === 0x2026
  );
}

export function 是安全字素码(码) {
  return (
    (码 >= 0x4e00 && 码 <= 0x9fff) ||
    (码 >= 0x20 && 码 <= 0x7e) ||
    (码 >= 0xff01 && 码 <= 0xff5e) ||
    (码 >= 0x3000 && 码 <= 0x3029) ||
    (码 >= 0x3030 && 码 <= 0x303f) ||
    (码 >= 0x2018 && 码 <= 0x201d) ||
    码 === 0x0a ||
    码 === 0xa0 ||
    码 === 0x2013 ||
    码 === 0x2014 ||
    码 === 0x2026
  );
}

export function 查找字素终点(文本, 起点) {
  let 窗口长度 = 64;
  while (true) {
    const 窗口终点 = Math.min(文本.length, 起点 + 窗口长度);
    for (const 字素信息 of 字素分段器.segment(文本.slice(起点, 窗口终点))) {
      const 终点 = 起点 + 字素信息.segment.length;
      if (终点 < 窗口终点 || 窗口终点 === 文本.length) {
        return 终点;
      }
      break;
    }
    窗口长度 *= 2;
  }
}

// 内容指纹：FNV-1a 32 位，跑在「文件解码后的原文」上，与管道规则无关。
// 用它判断"还是不是同一份文件"，不要用处理后的 状态.文本.length ——
// 后者会随换行/引号规则一起变，把同一份文件误判成另一本书。
// 2.9M 字的书实测 8~22ms，放在载入阶段可接受。
export function 计算内容哈希(文本) {
  let 哈希 = 2166136261 >>> 0;
  for (let idx = 0; idx < 文本.length; idx += 1) {
    哈希 ^= 文本.charCodeAt(idx);
    哈希 = Math.imul(哈希, 16777619) >>> 0;
  }
  return 哈希 >>> 0;
}
