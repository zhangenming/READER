import { 字素分段器, 汉字模式, 西文字素模式 } from './常量.js';

export function 是有效文本文件名(文件名) {
  return (
    typeof 文件名 === 'string' &&
    文件名.toLowerCase().endsWith('.txt') &&
    !文件名.includes('/') &&
    !文件名.includes('\\')
  );
}

export function 是汉字(字) {
  const 码点 = 字.codePointAt(0);
  return (
    (码点 >= 0x3400 && 码点 <= 0x4dbf) ||
    (码点 >= 0x4e00 && 码点 <= 0x9fff) ||
    (码点 >= 0xf900 && 码点 <= 0xfaff) ||
    (码点 > 0x7f && 汉字模式.test(字))
  );
}

export function 是阅读字符码(码) {
  return (
    (码 >= 0x4e00 && 码 <= 0x9fff) ||
    (码 >= 0x3400 && 码 <= 0x4dbf) ||
    (码 >= 0x61 && 码 <= 0x7a) ||
    (码 >= 0x41 && 码 <= 0x5a) ||
    (码 >= 0x30 && 码 <= 0x39)
  );
}

// 句内停顿标点（含换行 = 段落边界）：作为句段边界，本身不计负担
export function 是句内停顿码(码) {
  return (
    码 === 0x0a || // 换行（物理段落边界）
    (码 >= 0x3000 && 码 <= 0x303f) || // CJK 标点（，。！？；：、…「」《》等）
    (码 >= 0xff00 && 码 <= 0xffef) || // 全角形式（，。！？：；（））
    码 === 0x2026 || // …（省略号）
    (码 >= 0x2014 && 码 <= 0x2015) || // ——（破折号）
    (码 >= 0x2018 && 码 <= 0x201d) || // ‘’ “”（弯引号）
    码 === 0x2c || // ,（西文逗号）
    码 === 0x2e || // .
    码 === 0x3b || // ;
    码 === 0x3a || // :
    码 === 0x21 || // !
    码 === 0x3f // ?
  );
}

export function 是西文字素(字素) {
  return 是西文范围(字素, 0, 字素.length);
}

// 数字（0-9、零~九、〇、两、十百千万亿，含小数点）：整段字素全部为数字字符时才判定为数字，
// 连续西文数字（如 "1984"）会被聚合成一个片段，故需按整段匹配；
// 允许小数点，使 "3.14" 这类小数整体作为数字高亮。
const 数字字素模式 = /^[0-9〇零一二两三四五六七八九.十百千万亿]+$/u;
export function 是数字字素(字素) {
  return 数字字素模式.test(字素);
}

export function 是西文范围(文本, 起点, 终点) {
  for (let idx = 起点; idx < 终点; idx += 1) {
    const 码 = 文本.charCodeAt(idx);
    if (
      (码 >= 0x20 && 码 <= 0x7e) ||
      码 === 0xa0 ||
      (码 >= 0xff10 && 码 <= 0xff19) ||
      (码 >= 0xff21 && 码 <= 0xff3a) ||
      (码 >= 0xff41 && 码 <= 0xff5a)
    ) {
      continue;
    }
    if (
      (码 >= 0x4e00 && 码 <= 0x9fff) ||
      (码 >= 0xff01 && 码 <= 0xff5e) ||
      (码 >= 0x3000 && 码 <= 0x3020 && 码 !== 0x3007) ||
      (码 >= 0x2018 && 码 <= 0x201d) ||
      码 === 0x0a ||
      码 === 0x2013 ||
      码 === 0x2014 ||
      码 === 0x2026
    ) {
      return false;
    }
    return 西文字素模式.test(
      起点 === 0 && 终点 === 文本.length ? 文本 : 文本.slice(起点, 终点),
    );
  }
  return 终点 > 起点;
}

export function 是方块字素码(码) {
  return (
    (码 >= 0x4e00 && 码 <= 0x9fff) ||
    (码 >= 0x3400 && 码 <= 0x4dbf) ||
    (码 >= 0xf900 && 码 <= 0xfaff) ||
    (码 >= 0x3000 && 码 <= 0x303f) ||
    (码 >= 0xff01 && 码 <= 0xff5e) ||
    (码 >= 0x2018 && 码 <= 0x201d) ||
    码 === 0x2013 ||
    码 === 0x2014 ||
    码 === 0x2026
  );
}

export function 是安全字素码(码) {
  return (
    (码 >= 0x4e00 && 码 <= 0x9fff) ||
    (码 >= 0x20 && 码 <= 0x7e) ||
    (码 >= 0xff01 && 码 <= 0xff5e) ||
    (码 >= 0x3000 && 码 <= 0x3029) ||
    (码 >= 0x3030 && 码 <= 0x303f) ||
    (码 >= 0x2018 && 码 <= 0x201d) ||
    码 === 0x0a ||
    码 === 0xa0 ||
    码 === 0x2013 ||
    码 === 0x2014 ||
    码 === 0x2026
  );
}

export function 查找字素终点(文本, 起点) {
  let 窗口长度 = 64;
  while (true) {
    const 窗口终点 = Math.min(文本.length, 起点 + 窗口长度);
    for (const 字素信息 of 字素分段器.segment(文本.slice(起点, 窗口终点))) {
      const 终点 = 起点 + 字素信息.segment.length;
      if (终点 < 窗口终点 || 窗口终点 === 文本.length) {
        return 终点;
      }
      break;
    }
    窗口长度 *= 2;
  }
}
