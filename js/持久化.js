// 缓存也是本次会话的数据库工作副本；落盘失败时保留内存变更，后续保存可继续重试。

export function 读取持久化数据() {
  const 读取结果 = 尝试读取持久化快照();
  if ('错误' in 读取结果) {
    throw 读取结果.错误;
  }
  const 数据 = 解析持久化快照(读取结果.快照);
  持久化回退 = null;
  return 数据;
}

// 业务入口的显式恢复策略：读取失败时只在内存中使用空数据库。损坏数据会保留快照，
// 首次保存必须先写入独立备份；存储本身不可访问时禁止写入，避免覆盖未知原值。
export function 读取持久化数据或新建() {
  const 读取结果 = 尝试读取持久化快照();
  if ('错误' in 读取结果) {
    return 使用持久化回退('不可访问', null, 读取结果.错误);
  }

  try {
    const 数据 = 解析持久化快照(读取结果.快照);
    持久化回退 = null;
    return 数据;
  } catch (错误) {
    return 使用持久化回退('损坏', 读取结果.快照, 错误);
  }

  function 使用持久化回退(类型, 快照, 错误) {
    const 快照未变化 =
      持久化回退?.类型 === 类型 &&
      (快照 === null ||
        (持久化回退.快照?.原始数据 === 快照.原始数据 &&
          持久化回退.快照?.旧原始数据 === 快照.旧原始数据));
    if (!快照未变化) {
      持久化回退 = {
        类型,
        快照,
        数据: { 当前文件名: '', 文本状态: {} },
      };
      console.error(
        类型 === '损坏'
          ? '[阅读器] 持久化数据损坏，首次重建前将备份原始值'
          : '[阅读器] 持久化存储不可访问，已暂用内存空数据库',
        错误,
      );
    }
    return 持久化回退.数据;
  }
}

function 尝试读取持久化快照() {
  try {
    const 原始数据 = localStorage.getItem(持久化键);
    return {
      快照: {
        原始数据,
        旧原始数据: 原始数据 === null ? localStorage.getItem(旧持久化键) : null,
      },
    };
  } catch (错误) {
    return { 错误 };
  }
}

function 解析持久化快照({ 原始数据, 旧原始数据 }) {
  if (原始数据 !== null) {
    if (持久化缓存?.版本 === 'v2' && 持久化缓存.原始数据 === 原始数据) {
      return 持久化缓存.数据;
    }
    const 数据 = JSON.parse(原始数据);
    if (
      !数据 ||
      typeof 数据 !== 'object' ||
      typeof 数据.当前文件名 !== 'string' ||
      !数据.文本状态 ||
      typeof 数据.文本状态 !== 'object' ||
      Array.isArray(数据.文本状态)
    ) {
      throw new TypeError('持久化的文本状态数据库格式无效');
    }
    持久化缓存 = { 版本: 'v2', 原始数据, 旧原始数据: null, 数据 };
    return 数据;
  }

  if (旧原始数据 === null) {
    if (持久化缓存?.版本 === '空' && 持久化缓存.旧原始数据 === null) {
      return 持久化缓存.数据;
    }
    const 数据 = { 当前文件名: '', 文本状态: {} };
    持久化缓存 = { 版本: '空', 原始数据: null, 旧原始数据: null, 数据 };
    return 数据;
  }
  if (持久化缓存?.版本 === 'v1' && 持久化缓存.旧原始数据 === 旧原始数据) {
    return 持久化缓存.数据;
  }
  const 旧状态 = JSON.parse(旧原始数据);
  if (!旧状态 || typeof 旧状态 !== 'object') {
    throw new TypeError('旧版持久化阅读状态格式无效');
  }
  if (!是有效文本文件名(旧状态.文件名)) {
    const 数据 = { 当前文件名: '', 文本状态: {} };
    持久化缓存 = {
      版本: 'v1',
      原始数据: null,
      旧原始数据,
      数据,
    };
    return 数据;
  }
  const 数据 = {
    当前文件名: 旧状态.文件名,
    文本状态: { [旧状态.文件名]: 旧状态 },
  };
  持久化缓存 = {
    版本: 'v1',
    原始数据: null,
    旧原始数据,
    数据,
  };
  return 数据;
}

export function 安排保存持久化状态() {
  window.clearTimeout(状态.保存计时器);
  状态.保存计时器 = window.setTimeout(保存持久化状态, 持久化保存防抖毫秒);
}

export function 保存持久化状态() {
  if (!状态.文件名 || !状态.行起点列表.length) {
    return;
  }

  window.clearTimeout(状态.保存计时器);
  状态.保存计时器 = 0;
  结转未入账滚动毫秒();
  结转前台停留时长();
  const 阅读位置 = 读取阅读位置();
  const 持久化数据 = 读取持久化数据或新建();
  const 本次回退 = 持久化回退?.数据 === 持久化数据 ? 持久化回退 : null;
  持久化数据.当前文件名 = 状态.文件名;
  持久化数据.前台停留统计 = {
    ...前台停留统计快照(),
    每日激活时段: 激活时段统计快照().每日时段,
  };
  持久化数据.自动滚动统计 = {
    日期: 统计.今日滚动日期,
    今日毫秒: 统计.今日滚动毫秒,
    书籍毫秒: Object.fromEntries(统计.今日书籍滚动毫秒),
    每日书籍毫秒: 每日滚动毫秒转对象(),
    每日时段: 滚动时段统计快照().每日时段,
  };
  持久化数据.文本状态[状态.文件名] = {
    文件名: 状态.文件名,
    文本长度: 状态.文本.length,
    ...阅读位置,
    总滚动毫秒: 统计.书籍滚动毫秒.get(状态.文件名) ?? 0,
    当前关键词id: 状态.当前关键词id,
    关键词排序: 状态.关键词排序,
    关键词面板展开: 状态.关键词面板展开,
    自动滚动速度: 状态.自动滚动速度,
    字号: 状态.字号,
    行高: 状态.行高,
    当前字体标签: 外观.当前字体标签,
    字体: { 引号内: 字体设置.引号内, 引号外: 字体设置.引号外 },
    字体粗细: {
      引号内: 字体粗细设置.引号内,
      引号外: 字体粗细设置.引号外,
    },
    字体颜色: {
      引号内: 字体颜色设置.引号内,
      引号外: 字体颜色设置.引号外,
    },
    内置字词颜色: 外观.内置字词颜色,
    关键词样式: { 颜色: 外观.关键词颜色, 粗细: 外观.关键词粗细 },
    奇偶行颜色: { ...奇偶行颜色 },
    页面背景色: 外观.页面背景色,
    纸面色: 外观.纸面色,
    引文背景色启用: 外观.引文背景色启用,
    引文背景色: { ...引文背景色 },
    引文边框启用: 外观.引文边框启用,
    换行标记启用: 外观.换行标记启用,
    阶梯段落启用: 外观.阶梯段落启用,
    关键词列表: 状态.关键词列表
      .filter(function 排除临时关键词(关键词) {
        return !关键词.临时;
      })
      .map(function 序列化关键词(关键词) {
        return {
          id: 关键词.id,
          文本: 关键词.文本,
          当前命中idx: 关键词.当前命中idx,
          配色idx: 关键词.配色idx,
        };
      }),
    查找历史: 状态.查找历史,
  };
  // 只容错 localStorage 的可预期写入失败；序列化失败代表内存状态已异常，直接暴露。
  const 序列化数据 = JSON.stringify(持久化数据);
  if (本次回退?.类型 === '不可访问') {
    if (!本次回退.保存警告已记录) {
      本次回退.保存警告已记录 = true;
      console.warn('[阅读器] 持久化存储不可访问，已跳过保存以免覆盖未知原值');
    }
    return;
  }
  const 序列化损坏快照 = 本次回退 ? JSON.stringify(本次回退.快照) : null;
  let 保存阶段 = '保存持久化状态';
  try {
    if (序列化损坏快照 !== null) {
      保存阶段 = '备份损坏持久化数据';
      localStorage.setItem(损坏持久化备份键, 序列化损坏快照);
      保存阶段 = '重建持久化状态';
    }
    localStorage.setItem(持久化键, 序列化数据);
    持久化缓存 = {
      版本: 'v2',
      原始数据: 序列化数据,
      旧原始数据: null,
      数据: 持久化数据,
    };
    持久化回退 = null;
  } catch (错误) {
    // 隐私模式 / 配额满时 setItem 会抛异常；备份失败时不会继续覆盖损坏原值。
    console.warn(`[阅读器] ${保存阶段}失败`, 错误);
  }

  function 每日滚动毫秒转对象() {
    const 结果 = {};
    for (const [文件名, 日期表] of 统计.书籍每日滚动毫秒) {
      const 项 = {};
      for (const [日期, 毫秒] of 日期表) {
        if (毫秒 > 0) 项[日期] = 毫秒;
      }
      if (Object.keys(项).length) 结果[文件名] = 项;
    }
    return 结果;
  }
}

export function 读取阅读位置() {
  const 行位置 = 获取静止滚动位置() / 状态.行高;
  const 顶部行idx = Math.min(状态.行起点列表.length - 1, Math.floor(行位置));
  return {
    阅读偏移: 状态.行起点列表[顶部行idx],
    行内比例: 行位置 - 顶部行idx,
  };
}

export function 计算阅读位置(阅读位置) {
  const 阅读偏移 = Math.min(状态.文本.length, Math.max(0, 阅读位置.阅读偏移));
  const 行内比例 = Math.min(1, Math.max(0, 阅读位置.行内比例));
  return (查找偏移所在行(阅读偏移) + 行内比例) * 状态.行高;
}
