// 统计弹窗只负责展示，不参与计时或持久化。
//
// 两张表吃同一份数据：js/滚动时段.js 与 js/可见时段.js 里的按书起止时刻（快照含进行中段）。
// 三笔账全部由那些段求和得到，谁也不含谁：
//   总计 = 可见 ∪ 滚动 —— 开着页面在读的全部时间，也就是轴上那条铺开到底的浅灰带
//   滚动 = 滚动段     —— 压在带上的深色块（自动滚动与按住方向键同算一段）
//   激活 = 可见 − 滚动 —— 带子露出来的部分：开着页面但没在滚（手动读、停顿、开弹窗）
// 恒等式 激活 + 滚动 = 总计 是构造出来的，不是巧合：差集与并集把同一条带切成两段。
//
// 时段记录出现之前的老日子没有起止时刻，只能在「某书某日一段都没有」时回落旧毫秒账，
// 回落的日子画不出带子（照实留白），但上表的累计数不会凭空丢一截。
//
// 本模块只 import 时段集合.js（纯代数），保持无 DOM 依赖，单测可直接调用。

import { 合并时段, 差集时段, 时段总秒, 规范时段 } from './时段集合.js';

export { 合并时段, 差集时段 };

const 每日秒数 = 86_400;
const 未分书键 = '';

export function 格式化统计时长(毫秒) {
  const 有效毫秒 = Number.isFinite(毫秒) ? Math.max(0, 毫秒) : 0;
  if (有效毫秒 > 0 && 有效毫秒 < 60_000) return '不足 1 分钟';
  const 分钟 = Math.floor(有效毫秒 / 60_000);
  return 分钟 < 60
    ? `${分钟} 分钟`
    : `${Math.floor(分钟 / 60)} 小时 ${分钟 % 60} 分钟`;
}

export function 格式化统计日期(日期串, 今天) {
  if (typeof 日期串 !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(日期串)) {
    return 日期串 == null ? '' : String(日期串);
  }
  if (日期串 === 今天) return '今天';
  const 年 = 日期串.slice(0, 4);
  const 月 = Number(日期串.slice(5, 7));
  const 日 = Number(日期串.slice(8, 10));
  return typeof 今天 === 'string' && 今天.startsWith(年)
    ? `${月}月${日}日`
    : `${年}年${月}月${日}日`;
}

// —— 时段几何：轴窗口 / 刻度 / 色块 / 时刻与时长格式化（纯函数）——

// 把 { 日期 -> { 书名 -> 段列表 } } 或 [[日期, 段列表], ...] 归一成 [[日期, 段列表], ...]
function 归一时段条目(每日时段) {
  if (每日时段 instanceof Map) return [...每日时段];
  if (Array.isArray(每日时段)) {
    return 每日时段.filter((项) => Array.isArray(项) && typeof 项[0] === 'string');
  }
  return Object.entries(每日时段 ?? {});
}

// 把 { 日期 -> { 书名 -> 段列表 } }（新形状）或 { 日期 -> 段列表 }（旧的不分书形状）
// 里的段列表统一取出来。
function 取段列表们(值) {
  if (值 instanceof Map) return [...值.values()];
  if (Array.isArray(值)) return [值];
  if (值 && typeof 值 === 'object') return Object.values(值);
  return [];
}

// 只留有段的日期；两类时段（滚动 / 可见）按日期取并集渲染成一行
function 取有时段的条目(每日时段) {
  return 归一时段条目(每日时段).filter(([, 值]) =>
    取段列表们(值).some((段列表) => 段列表 && 段列表.length),
  );
}

// 所有行共用一条时间轴：窗口 = 全部日期全部段的最早起点 ~ 最晚终点（当日秒）。
// 新一天出现更早/更晚的数据时窗口自动外扩；空隙不画进轴里。无数据返回 null。
export function 计算时段窗口(每日时段) {
  let 起秒 = Infinity;
  let 止秒 = -Infinity;
  for (const [, 值] of 归一时段条目(每日时段)) {
    for (const 段列表 of 取段列表们(值)) {
      for (const 段 of 段列表 ?? []) {
        if (!Array.isArray(段) || 段.length < 2) continue;
        const [起, 止] = 段;
        if (Number.isFinite(起) && Number.isFinite(止) && 止 > 起) {
          起秒 = Math.min(起秒, 起);
          止秒 = Math.max(止秒, 止);
        }
      }
    }
  }
  return 起秒 < 止秒 ? { 起秒, 止秒: Math.min(止秒, 每日秒数) } : null;
}

// 共用轴可能横跨十几个小时，刻度步长随窗口跨度自适应，保证标签不挤在一起。
export function 计算刻度步长(窗口) {
  const 跨度 = 窗口 ? 窗口.止秒 - 窗口.起秒 : 0;
  for (const 步长 of [3600, 7200, 10800, 21600, 43200]) {
    if (跨度 / 步长 <= 6) return 步长;
  }
  return 43200;
}

// 轴内的整点（步长）刻度，不含与窗口起点重合者；窗口跨不过一个步长时为空，只显首尾时刻。
export function 计算整点刻度(窗口, 步长秒 = 计算刻度步长(窗口)) {
  if (!窗口 || !(窗口.止秒 > 窗口.起秒) || !(步长秒 > 0)) return [];
  const 刻度 = [];
  for (let 秒 = Math.ceil(窗口.起秒 / 步长秒) * 步长秒; 秒 < 窗口.止秒; 秒 += 步长秒) {
    if (秒 === 窗口.起秒) continue;
    刻度.push({ 秒, 标签: `${Math.floor(秒 / 3600)}:00` });
  }
  return 刻度;
}

// 段 → 轴上的百分比几何（超出窗口的部分裁掉；宽度可为 0，由 CSS min-width 兜底可见）。
export function 时段百分比(当日秒, 窗口) {
  if (!窗口 || !(窗口.止秒 > 窗口.起秒)) return 0;
  return ((当日秒 - 窗口.起秒) / (窗口.止秒 - 窗口.起秒)) * 100;
}

// 一组段的总秒数（重叠段请先用 合并时段 并掉，否则会重复计时）。
export function 计算时段总秒(段列表) {
  return 时段总秒(段列表);
}

export function 计算时段布局(段列表, 窗口) {
  if (!窗口 || !(窗口.止秒 > 窗口.起秒)) return [];
  return 规范时段(段列表).map(([起, 止]) => {
    const 起秒 = Math.min(Math.max(起, 窗口.起秒), 窗口.止秒);
    const 止秒 = Math.min(Math.max(止, 窗口.起秒), 窗口.止秒);
    return {
      起,
      止,
      左: 时段百分比(起秒, 窗口),
      宽: 时段百分比(止秒, 窗口) - 时段百分比(起秒, 窗口),
    };
  });
}

export function 格式化时段时刻(当日秒) {
  const 总 = Math.max(0, Math.min(每日秒数 - 1, Math.floor(当日秒) || 0));
  const 补零 = (值) => String(值).padStart(2, '0');
  return `${补零(Math.floor(总 / 3600))}:${补零(Math.floor(总 / 60) % 60)}:${补零(总 % 60)}`;
}

// 轴首尾只标到分（秒在色块悬停提示里给），窄屏上标签才不会互相压字。
export function 格式化轴时刻(当日秒) {
  return 格式化时段时刻(当日秒).slice(0, 5);
}

export function 格式化时段时长(秒数) {
  const 总 = Math.max(0, Math.floor(Number.isFinite(秒数) ? 秒数 : 0));
  const 小时 = Math.floor(总 / 3600);
  const 分 = Math.floor(总 / 60) % 60;
  const 秒 = 总 % 60;
  if (小时) return `${小时} 小时 ${分} 分`;
  if (分) return `${分} 分 ${秒} 秒`;
  return `${秒} 秒`;
}

// 弹窗右侧那几列读数只到分：秒留给色块悬停提示与无障碍标签。
// 不足 1 分钟不写成「0 分」，与 格式化统计时长 同一口径。
export function 格式化时长到分(秒数) {
  const 总 = Math.max(0, Math.floor(Number.isFinite(秒数) ? 秒数 : 0));
  if (总 > 0 && 总 < 60) return '不足 1 分钟';
  const 分钟 = Math.floor(总 / 60);
  return 分钟 < 60 ? `${分钟} 分` : `${Math.floor(分钟 / 60)} 小时 ${分钟 % 60} 分`;
}

// 合计按各行「显示到分」的值相加：拿计算器竖着加这一列要能加出来
// （先加秒再取整会凭空多出几分钟）。
function 到分秒(秒数) {
  return Math.floor(Math.max(0, 秒数) / 60) * 60;
}

// —— 三笔账的取数（纯函数，可直接单测）——
// 入参都是持久化的形状：{ 日期: { 书名: [[起当日秒, 止当日秒], ...] } }
// 旧版时段不分书，整天的段直接挂在日期下（数组），一律按「未分书」读回。
export function 汇总书籍时间账({
  滚动账 = {},
  可见账 = {},
  旧滚动每日毫秒 = {},
  旧可见每日毫秒 = {},
  旧书总毫秒 = {},
  旧书总可见毫秒 = {},
} = {}) {
  const 按日 = new Map(); // 日期 -> Map(书名 -> 账)
  const 取按书 = (每日) => {
    const 结果 = new Map();
    for (const [日期, 值] of Object.entries(每日 ?? {})) {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(日期)) continue;
      if (Array.isArray(值)) 结果.set(日期, new Map([[未分书键, 值]]));
      else if (值 && typeof 值 === 'object') {
        const 按书 = new Map(Object.entries(值).map(([书名, 段]) => [书名, 段]));
        结果.set(日期, 按书);
      }
    }
    return 结果;
  };
  const 滚动按日 = 取按书(滚动账);
  const 可见按日 = 取按书(可见账);
  // 老数据的毫秒账是「书 -> 日」组织的，先摊平成「日 -> 书」才能和时段按同一把日期对齐
  const 旧滚动按日 = 摊平旧账(旧滚动每日毫秒);
  const 旧可见按日 = 摊平旧账(旧可见每日毫秒);

  const 日期集合 = new Set([
    ...滚动按日.keys(),
    ...可见按日.keys(),
    ...旧滚动按日.keys(),
    ...旧可见按日.keys(),
  ]);

  for (const 日期 of 日期集合) {
    const 书集合 = new Set([
      ...(滚动按日.get(日期)?.keys() ?? []),
      ...(可见按日.get(日期)?.keys() ?? []),
      ...(旧滚动按日.get(日期)?.keys() ?? []),
      ...(旧可见按日.get(日期)?.keys() ?? []),
    ]);
    const 行表 = new Map();
    for (const 书名 of 书集合) {
      const 滚动段 = 规范时段(滚动按日.get(日期)?.get(书名) ?? []);
      const 可见段 = 规范时段(可见按日.get(日期)?.get(书名) ?? []);
      if (滚动段.length || 可见段.length) {
        // 有段就只用段：图、行、合计三处同一本账
        const 激活段 = 差集时段(可见段, 滚动段);
        const 总计段 = 合并时段(可见段, 滚动段);
        行表.set(书名, {
          滚动段,
          总计段,
          滚动秒: 时段总秒(滚动段),
          激活秒: 时段总秒(激活段),
          总计秒: 时段总秒(总计段),
          有段: true,
        });
        continue;
      }
      const 旧滚动毫秒 = 旧滚动按日.get(日期)?.get(书名) ?? 0;
      const 旧可见毫秒 = 旧可见按日.get(日期)?.get(书名) ?? 0;
      const 滚动秒 = Math.max(0, 旧滚动毫秒) / 1000;
      // 旧「前台停留」就是当时的「可见」，本来含滚动；没有这笔账时总计只能等于滚动
      const 总计秒 = Math.max(旧可见毫秒 / 1000, 滚动秒);
      行表.set(书名, {
        滚动段: [],
        总计段: [],
        滚动秒,
        激活秒: Math.max(0, 总计秒 - 滚动秒),
        总计秒,
        有段: false,
      });
    }
    if (行表.size) 按日.set(日期, 行表);
  }

  // 按书累计 = 逐日相加；再把旧版「历史总毫秒」里比逐日和多出来的那部分补进来。
  // 那笔差额来自分日记录出现之前的日子——既没有段也没有按日毫秒，只能整体补在滚动/总计上，
  // 补出来的未知段时间归给「激活与总计的差额」，保证 激活 + 滚动 = 总计 不被破坏。
  const 按书 = new Map();
  for (const [日期, 行表] of 按日) {
    for (const [书名, 账] of 行表) {
      const 累计 = 按书.get(书名) ?? { 滚动秒: 0, 激活秒: 0, 总计秒: 0 };
      累计.滚动秒 += 账.滚动秒;
      累计.激活秒 += 账.激活秒;
      累计.总计秒 += 账.总计秒;
      按书.set(书名, 累计);
    }
  }
  const 旧书们 = new Set([
    ...Object.keys(旧书总毫秒),
    ...Object.keys(旧书总可见毫秒),
  ]);
  for (const 书名 of 旧书们) {
    const 累计 = 按书.get(书名) ?? { 滚动秒: 0, 激活秒: 0, 总计秒: 0 };
    const 差额滚动 = Math.max(0, (旧书总毫秒[书名] ?? 0) / 1000 - 累计.滚动秒);
    const 差额总计 = Math.max(0, (旧书总可见毫秒[书名] ?? 0) / 1000 - 累计.总计秒);
    // 补进来的那截是「不知道是哪天的滚动时间」，它必然也开着页面，所以总计至少要跟着滚动走，
    // 否则 激活 + 滚动 = 总计 会被旧账撑破（旧滚动累计 > 逐日总计 时就会这样）。
    const 补总计 = Math.max(差额总计, 差额滚动);
    累计.滚动秒 += 差额滚动;
    累计.总计秒 += 补总计;
    // 未知日期那截里，多出来的总计时间只能是「开着页面没在滚」，归激活
    累计.激活秒 += Math.max(0, 补总计 - 差额滚动);
    按书.set(书名, 累计);
  }

  return { 按日, 按书 };
}

// 一天一行：把当天各本书的段并到同一条轴上。同一分钟在两本书上都有记录时只算一次，
// 所以合并后的总计可以小于组内各行相加——轴回答的是「这天页面开着多久」，不是「各本书相加多久」。
// 激活仍取 差集(总计, 滚动)，恒等式 激活 + 滚动 = 总计 在日级照样成立。
export function 合并当日账(账列表) {
  const 有段 = 账列表.filter((账) => 账.有段);
  const 滚动段 = 合并时段(...有段.map((账) => 账.滚动段));
  const 总计段 = 合并时段(...有段.map((账) => 账.总计段));
  const 滚动秒 = 时段总秒(滚动段);
  return {
    滚动段,
    总计段,
    滚动秒,
    激活秒: 时段总秒(差集时段(总计段, 滚动段)),
    总计秒: 时段总秒(总计段),
  };
}

function 摊平旧账(旧每日毫秒) {
  const 结果 = new Map(); // 日期 -> Map(书名 -> 毫秒)
  for (const [书名, 日期表] of Object.entries(旧每日毫秒 ?? {})) {
    if (!日期表 || typeof 日期表 !== 'object') continue;
    for (const [日期, 毫秒] of Object.entries(日期表)) {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(日期) || !Number.isFinite(毫秒) || 毫秒 <= 0) continue;
      const 表 = 结果.get(日期) ?? new Map();
      表.set(书名, (表.get(书名) ?? 0) + 毫秒);
      结果.set(日期, 表);
    }
  }
  return 结果;
}

