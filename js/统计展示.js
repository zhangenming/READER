import { 状态, 统计 } from './状态.js';

// 滚动时长 / 剩余阅读时间的格式化展示。
// 从 自动滚动.js 拆出，供 滚动条 与 app.js 共享，避免「滚动条 → 自动滚动 → 持久化 → …」参与依赖环。

// 将自动滚动毫秒格式化为固定一位小数的小时数
export function 格式化滚动小时(毫秒) {
  const 小时 = Math.max(0, 毫秒) / 3_600_000;
  return `${小时.toFixed(1)}h`;
}

// 将剩余秒数格式化为固定一位小数的小时数（如 1.7h）
export function 格式化剩余滚动时间(秒数) {
  return 格式化滚动小时((Number.isFinite(秒数) ? 秒数 : 0) * 1000);
}

// 将本次自动滚动毫秒格式化为固定一位小数的分钟数
export function 格式化当前滚动分钟(毫秒) {
  const 分钟 = Math.max(0, 毫秒) / 60_000;
  return `${分钟.toFixed(1)}分`;
}

// 第一行（当前自动滚动时长）后的括号：今日全部书籍的自动滚动总时长
export function 今日滚动后缀() {
  return `（${格式化滚动小时(统计.今日滚动毫秒 + 统计.未入账滚动毫秒)}）`;
}

// 第二行（剩余时长）后的括号：当前这本书今天的自动滚动时长
export function 今日本书滚动后缀() {
  const 今日毫秒 = (统计.今日书籍滚动毫秒.get(状态.文件名) ?? 0) + 统计.未入账滚动毫秒;
  return `（${格式化滚动小时(今日毫秒)}）`;
}
