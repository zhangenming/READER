import { 状态, 统计 } from './状态.js';
import { 获取书籍前台毫秒, 书籍每日前台毫秒 } from './前台停留.js';
import {
  滚动时段统计快照,
  滚动当日总秒,
  本书滚动当日总秒,
} from './滚动时段.js';
import { 可见时段统计快照 } from './可见时段.js';
// 逐日逐书的时间账由 阅读统计.js 的纯函数算（那里可直接单测），这里只做再导出，
// 免得取数与算账两处各写一套规则。
import { 汇总书籍时间账 } from './阅读统计.js';

export { 汇总书籍时间账 };

// 滚动 / 激活 / 总计三笔时间账的取数与格式化展示。
// 从 自动滚动.js 拆出，供 滚动条、内容选择弹窗、阅读统计弹窗共享，
// 避免「滚动条 → 自动滚动 → 持久化 → …」参与依赖环。

// 时段账是唯一的时长来源：几点到几点就是账本，多久 = 段求和。
// 旧版那本按书按日的毫秒账只作为「没有时段的日期」的回落值（见 汇总书籍时间账）。
export function 快照时间账(此刻 = Date.now()) {
  return {
    滚动账: 滚动时段统计快照(此刻).每日时段,
    可见账: 可见时段统计快照(此刻).每日时段,
    旧滚动每日毫秒: 旧每日毫秒转对象(统计.书籍每日滚动毫秒),
    旧可见每日毫秒: 旧每日毫秒转对象(书籍每日前台毫秒),
    旧书总毫秒: 旧书总毫秒转对象(),
    旧书总可见毫秒: 旧书总前台毫秒转对象(),
  };
}

function 旧每日毫秒转对象(每日表) {
  const 结果 = {};
  for (const [文件名, 日期表] of 每日表) {
    const 项 = {};
    for (const [日期, 毫秒] of 日期表) 项[日期] = 毫秒;
    if (Object.keys(项).length) 结果[文件名] = 项;
  }
  return 结果;
}

function 旧书总毫秒转对象() {
  const 结果 = {};
  for (const [文件名, 毫秒] of 统计.书籍滚动毫秒) 结果[文件名] = 毫秒;
  return 结果;
}

function 旧书总前台毫秒转对象() {
  const 结果 = {};
  for (const 文件名 of 书籍每日前台毫秒.keys()) {
    结果[文件名] = 获取书籍前台毫秒(文件名);
  }
  return 结果;
}

// 全部书的时间账（累计），弹窗两张表与内容选择弹窗共用同一份，
// 免得两处并排显示的同一本书差出零点几小时。
export function 书籍时间账表(此刻 = Date.now()) {
  return 汇总书籍时间账(快照时间账(此刻)).按书;
}

// 一本书的三笔账（毫秒）；从没读过的书返回全零，由调用方决定留白还是写「—」。
export function 书籍时间账(文件名, 账表 = 书籍时间账表()) {
  const 账 = 账表.get(文件名);
  return {
    滚动毫秒: Math.round((账?.滚动秒 ?? 0) * 1000),
    激活毫秒: Math.round((账?.激活秒 ?? 0) * 1000),
    总计毫秒: Math.round((账?.总计秒 ?? 0) * 1000),
  };
}

// 今日全部书籍的滚动总时长（右下角第一行右槽）；含正在进行的这段。
export function 今日滚动后缀(此刻 = Date.now()) {
  return 格式化滚动分钟(滚动当日总秒(今日(), 此刻) * 1000);
}

// 当前这本书今天的滚动时长（右下角第二行左槽）；含正在进行的这段。
export function 今日本书滚动后缀(此刻 = Date.now()) {
  const 文件名 = 状态.文件名;
  if (!文件名) return 格式化滚动小时(0);
  return 格式化滚动小时(本书滚动当日总秒(文件名, 今日(), 此刻) * 1000);
}

function 今日() {
  const 日期 = new Date();
  const 补零 = (值) => String(值).padStart(2, '0');
  return `${日期.getFullYear()}-${补零(日期.getMonth() + 1)}-${补零(日期.getDate())}`;
}

// 将毫秒格式化为固定一位小数的小时数
export function 格式化滚动小时(毫秒) {
  const 小时 = Math.max(0, 毫秒) / 3_600_000;
  return `${小时.toFixed(1)}h`;
}

// 将剩余秒数格式化为固定一位小数的小时数（如 1.7h）
export function 格式化剩余滚动时间(秒数) {
  return 格式化滚动小时((Number.isFinite(秒数) ? 秒数 : 0) * 1000);
}

// 将毫秒格式化为固定一位小数的分钟数
export function 格式化滚动分钟(毫秒) {
  const 分钟 = Math.max(0, 毫秒) / 60_000;
  return `${分钟.toFixed(1)}m`;
}
