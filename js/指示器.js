import { 指示器刻度高度, 指示器基础透明度 } from './常量.js';
import { 元素, 状态 } from './状态.js';
import { 查找关键词, 渲染关键词面板, 获取关键词配色 } from './关键词.js';
import { 更新滚动块, 读取滚动条度量, 轨道中心转滚动位置 } from './滚动条.js';
import { 查找首个不小于的命中, 查找首个相交命中 } from './跳转动画.js';

const 当前指示器上下文 = 元素.关键词指示器.getContext('2d');
const 悬停指示器上下文 = 元素.悬停关键词指示器.getContext('2d');
if (!当前指示器上下文 || !悬停指示器上下文) {
  throw new Error('当前浏览器无法创建关键词指示器画布上下文');
}

export function 更新关键词指示器() {
  渲染关键词面板();
  更新滚动块();
  const 轨道高度 = 元素.自定义滚动条.clientHeight;
  const 容器高度 = 元素.滚动容器.clientHeight;
  const 滚动高度 = 元素.滚动容器.scrollHeight;
  const 视口度量 = { 轨道高度, 容器高度, 滚动高度 };
  const 当前关键词 = 查找关键词(状态.当前关键词id);
  const 悬停关键词 =
    状态.悬停关键词id === 状态.当前关键词id
      ? null
      : 查找关键词(状态.悬停关键词id);
  const 可绘制 = 状态.行起点列表.length && 滚动高度 > 容器高度;

  if (
    !可绘制 ||
    (!当前关键词?.命中位置.length && !悬停关键词?.命中位置.length)
  ) {
    元素.关键词指示器.hidden = true;
    元素.悬停关键词指示器.hidden = true;
    设置悬停指示器状态(false);
    状态.指示器缓存 = null;
    return;
  }

  const 像素比 = Math.min(3, window.devicePixelRatio || 1);
  const 画布高 = Math.max(1, Math.round(轨道高度 * 像素比));
  const 布局键 = [
    状态.排版键,
    画布高,
    轨道高度,
    容器高度,
    滚动高度,
    像素比,
  ].join('|');

  if (状态.指示器缓存?.布局键 !== 布局键) {
    状态.指示器缓存 = {
      布局键,
      底图缓存: new Map(),
      段缓存: new Map(),
    };
  }

  绘制单列指示器(元素.关键词指示器, 当前指示器上下文, 当前关键词, '当前');
  绘制单列指示器(元素.悬停关键词指示器, 悬停指示器上下文, 悬停关键词, '悬停');
  设置悬停指示器状态(!元素.悬停关键词指示器.hidden);

  function 绘制单列指示器(画布, 上下文, 关键词, 类型) {
    if (!关键词?.命中位置.length) {
      画布.hidden = true;
      return;
    }

    画布.hidden = false;
    const 画布宽 = Math.max(1, Math.round(画布.clientWidth * 像素比));
    if (画布.width !== 画布宽 || 画布.height !== 画布高) {
      画布.width = 画布宽;
      画布.height = 画布高;
    }

    const 底图键 = `${关键词.id}|${画布宽}|${类型}`;
    let 底图 = 状态.指示器缓存.底图缓存.get(底图键);
    if (!底图) {
      const 开始时间 = performance.now();
      const 原刻度缓存数 = 状态.指示器缓存.段缓存.size;
      底图 = 创建指示器底图(画布宽, 画布高, 像素比, 关键词, 类型, 视口度量);
      状态.指示器缓存.底图缓存.set(底图键, 底图);
      if (状态.指示器缓存.段缓存.size !== 原刻度缓存数) {
        console.info('[阅读器] 关键词指示器已重建', {
          类型,
          关键词: 关键词.文本,
          命中数: 关键词.命中位置.length,
          轨道像素高: 画布高,
          耗时毫秒: Math.round(performance.now() - 开始时间),
        });
      }
    }

    上下文.clearRect(0, 0, 画布宽, 画布高);
    上下文.drawImage(底图, 0, 0);
  }

  function 设置悬停指示器状态(正在显示) {
    元素.滚动块.classList.toggle('悬停关键词时隐藏', 正在显示);
    元素.滚动进度.classList.toggle('悬停关键词时左移', 正在显示);
  }
}

// 将剩余秒数格式化为固定一位小数的小时数（如 1.7h）

export function 创建指示器底图(画布宽, 画布高, 像素比, 主关键词, 类型, 视口度量) {
  const 底图 = document.createElement('canvas');
  底图.width = 画布宽;
  底图.height = 画布高;
  const 底图上下文 = 底图.getContext('2d');
  if (!底图上下文) {
    throw new Error('无法创建关键词指示器底图');
  }

  const 最小刻度高度 = Math.max(1, Math.round(指示器刻度高度 * 像素比));
  const 刻度 = 读取指示器刻度(主关键词, 画布高, 最小刻度高度, 视口度量);
  // 「当前」指示器位置固定且独立于配色，用纯黑在白色轨道上保持清晰；
  // 「悬停」仍沿用关键词配色，便于与正文高亮一致。
  底图上下文.fillStyle =
    类型 === '当前' ? '#000000' : 获取关键词配色(主关键词).深色;

  // 先以基础透明度铺出所有刻度，保证稀疏命中也可见
  const 段列表 = 刻度.刻度列表;
  底图上下文.globalAlpha = 指示器基础透明度;
  for (let idx = 0; idx < 段列表.length; idx += 2) {
    底图上下文.fillRect(0, 段列表[idx], 画布宽, 段列表[idx + 1] - 段列表[idx]);
  }

  // 再按逐像素命中密度叠加颜色，密集段越深，一眼可见分布重心
  if (刻度.最大密度 > 0) {
    for (let 像素idx = 0; 像素idx < 刻度.密度列表.length; 像素idx += 1) {
      const 密度 = 刻度.密度列表[像素idx];
      if (!密度) {
        continue;
      }
      底图上下文.globalAlpha =
        指示器基础透明度 +
        (1 - 指示器基础透明度) * Math.sqrt(密度 / 刻度.最大密度);
      底图上下文.fillRect(0, 像素idx, 画布宽, 1);
    }
  }
  底图上下文.globalAlpha = 1;
  return 底图;
}

/* 刻度与密度只跟版面与命中有关，与谁是主关键词无关，可以跨悬停切换复用。 */

export function 读取指示器刻度(关键词, 画布高, 最小刻度高度, 视口度量) {
  const 段缓存 = 状态.指示器缓存.段缓存;
  let 刻度 = 段缓存.get(关键词.id);
  if (!刻度) {
    刻度 = 创建指示器刻度(关键词, 画布高, 最小刻度高度, 视口度量);
    段缓存.set(关键词.id, 刻度);
  }
  return 刻度;
}

/* 逐轨道像素反查命中，代价只与轨道高度相关，与命中数量无关。 */

export function 创建指示器刻度(关键词, 画布高, 最小刻度高度, 视口度量) {
  const { 轨道高度, 容器高度, 滚动高度 } = 视口度量;
  const 总行数 = 状态.行起点列表.length;
  const 滚动条度量 = 读取滚动条度量(轨道高度, 容器高度, 滚动高度);
  const 画布比例 = 画布高 / 轨道高度;
  const 滚动块中心 = 滚动条度量.滚动块高度 / 2;
  const 末端滚动块中心 = 轨道高度 - 滚动块中心;
  const 段数组 = [];
  const 密度列表 = new Uint32Array(画布高);
  let 最大密度 = 0;
  let 段起点 = -1;
  let 像素idx = 0;

  for (; 像素idx < 画布高; 像素idx += 1) {
    const 轨道像素起点 = 像素idx / 画布比例;
    const 轨道像素终点 = (像素idx + 1) / 画布比例;
    const 位于顶部滚动块中心 =
      轨道像素起点 <= 滚动块中心 && 滚动块中心 < 轨道像素终点;
    const 位于底部滚动块中心 =
      轨道像素起点 <= 末端滚动块中心 && 末端滚动块中心 < 轨道像素终点;
    if (
      !位于顶部滚动块中心 &&
      !位于底部滚动块中心 &&
      (轨道像素终点 <= 滚动块中心 || 轨道像素起点 >= 末端滚动块中心)
    ) {
      if (段起点 >= 0) {
        段数组.push(段起点, 像素idx);
        段起点 = -1;
      }
      continue;
    }

    const 文档中心起点 = 位于顶部滚动块中心
      ? 0
      : 轨道中心转滚动位置(轨道像素起点, 滚动条度量) + 容器高度 / 2;
    const 文档中心终点 = 位于底部滚动块中心
      ? 滚动高度
      : 轨道中心转滚动位置(轨道像素终点, 滚动条度量) + 容器高度 / 2;
    const 行起点idx = Math.max(
      0,
      Math.min(总行数 - 1, Math.ceil(文档中心起点 / 状态.行高 - 0.5)),
    );
    const 行终点idx = Math.min(
      总行数,
      Math.max(Math.ceil(文档中心终点 / 状态.行高 - 0.5), 行起点idx + 1),
    );
    const 像素起点偏移 = 状态.行起点列表[行起点idx];
    const 命中idx = 查找首个相交命中(关键词, 像素起点偏移);
    const 像素终点偏移 =
      行终点idx < 总行数 ? 状态.行起点列表[行终点idx] : 状态.文本.length;
    const 有命中 =
      命中idx < 关键词.命中位置.length &&
      关键词.命中位置[命中idx] < 像素终点偏移;

    const 密度 =
      查找首个不小于的命中(关键词, 像素终点偏移) -
      查找首个不小于的命中(关键词, 像素起点偏移);
    密度列表[像素idx] = 密度;
    if (密度 > 最大密度) {
      最大密度 = 密度;
    }

    if (有命中) {
      if (段起点 < 0) {
        段起点 = 像素idx;
      }
    } else if (段起点 >= 0) {
      段数组.push(段起点, 像素idx);
      段起点 = -1;
    }
  }
  if (段起点 >= 0) {
    段数组.push(段起点, 像素idx);
  }

  return {
    刻度列表: 展开最小刻度(段数组, 画布高, 最小刻度高度),
    密度列表,
    最大密度,
  };
}

export function 展开最小刻度(段数组, 画布高, 最小刻度高度) {
  const 刻度列表 = [];
  for (let idx = 0; idx < 段数组.length; idx += 2) {
    let 起点 = 段数组[idx];
    let 终点 = 段数组[idx + 1];
    if (终点 - 起点 < 最小刻度高度) {
      起点 = Math.round((起点 + 终点 - 最小刻度高度) / 2);
      终点 = 起点 + 最小刻度高度;
      if (起点 < 0) {
        起点 = 0;
        终点 = Math.min(画布高, 最小刻度高度);
      }
      if (终点 > 画布高) {
        终点 = 画布高;
        起点 = Math.max(0, 画布高 - 最小刻度高度);
      }
    }

    if (刻度列表.length && 起点 <= 刻度列表[刻度列表.length - 1]) {
      刻度列表[刻度列表.length - 1] = Math.max(
        刻度列表[刻度列表.length - 1],
        终点,
      );
    } else {
      刻度列表.push(起点, 终点);
    }
  }
  return 刻度列表;
}
