export function 更新自动滚动速度() {
  const 显示速度 = String(Math.round(状态.自动滚动速度));
  元素.基础速度显示.textContent = `基 ${显示速度}`;
  元素.自动滚动按钮.setAttribute(
    'aria-label',
    `滚动，基准速度 ${显示速度}，自动适配内容密度，点击切换全屏`,
  );
}

