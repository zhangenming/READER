import { 元素, 状态, 统计 } from './状态.js';

// 自动滚动统计：滚动时长记账（今日按书分项、历史累计）与基准速度展示。
// 格式化展示已移入 统计展示.js；持久化读取改由 app.js 传入（载入自动滚动统计(数据)），
// 本模块不再依赖 持久化.js，断掉「自动滚动 → 持久化」依赖边。

export function 更新自动滚动速度() {
  const 显示速度 = String(Math.round(状态.自动滚动速度));
  元素.基础速度显示.textContent = `基 ${显示速度}`;
  元素.自动滚动按钮.setAttribute(
    'aria-label',
    `滚动，基准速度 ${显示速度}，自动适配内容密度，点击切换全屏`,
  );
}

export function 本地日期串(日期) {
  const 补零 = (值) => String(值).padStart(2, '0');
  return `${日期.getFullYear()}-${补零(日期.getMonth() + 1)}-${补零(
    日期.getDate(),
  )}`;
}

export function 确保今日滚动统计() {
  const 今天 = 本地日期串(new Date());
  if (统计.今日滚动日期 === 今天) {
    return;
  }
  if (状态.文件名 && 统计.未入账滚动毫秒 > 0) {
    统计.书籍滚动毫秒.set(
      状态.文件名,
      (统计.书籍滚动毫秒.get(状态.文件名) ?? 0) + 统计.未入账滚动毫秒,
    );
  }
  const 上一日期 = 统计.今日滚动日期;
  统计.今日滚动日期 = 今天;
  统计.今日滚动毫秒 = 0;
  统计.今日书籍滚动毫秒.clear();
  统计.未入账滚动毫秒 = 0;
  console.info('[阅读器] 自动滚动今日统计已重置', { 上一日期, 当前日期: 今天 });
}

// 把滚动会话中累计的未入账时长结转到今日总计、今日当前书与本书历史累计
export function 结转未入账滚动毫秒() {
  if (!状态.文件名 || 统计.未入账滚动毫秒 <= 0) {
    return;
  }
  确保今日滚动统计();
  if (统计.未入账滚动毫秒 <= 0) {
    return;
  }
  统计.今日滚动毫秒 += 统计.未入账滚动毫秒;
  统计.今日书籍滚动毫秒.set(
    状态.文件名,
    (统计.今日书籍滚动毫秒.get(状态.文件名) ?? 0) + 统计.未入账滚动毫秒,
  );
  统计.书籍滚动毫秒.set(
    状态.文件名,
    (统计.书籍滚动毫秒.get(状态.文件名) ?? 0) + 统计.未入账滚动毫秒,
  );
  统计.未入账滚动毫秒 = 0;
}

// 启动时从持久化数据恢复今日总时长、今日按书分项与每本书的历史累计时长。
// 数据由调用方（app.js）从 读取持久化数据() 取得并传入；null 表示读取失败，跳过恢复。
export function 载入自动滚动统计(数据) {
  if (!数据) {
    return;
  }
  const 持久统计 = 数据.自动滚动统计;
  const 今天 = 本地日期串(new Date());
  if (
    持久统计 &&
    typeof 持久统计 === 'object' &&
    持久统计.日期 === 今天 &&
    typeof 持久统计.今日毫秒 === 'number' &&
    Number.isFinite(持久统计.今日毫秒)
  ) {
    统计.今日滚动日期 = 今天;
    统计.今日滚动毫秒 = Math.max(0, 持久统计.今日毫秒);
    if (持久统计.书籍毫秒 !== undefined) {
      if (
        !持久统计.书籍毫秒 ||
        typeof 持久统计.书籍毫秒 !== 'object' ||
        Array.isArray(持久统计.书籍毫秒)
      ) {
        throw new TypeError('持久化的今日按书滚动统计格式无效');
      }
      for (const [文件名, 毫秒] of Object.entries(持久统计.书籍毫秒)) {
        if (typeof 毫秒 !== 'number' || !Number.isFinite(毫秒)) {
          throw new TypeError(`持久化的今日滚动时长无效：${文件名}`);
        }
        统计.今日书籍滚动毫秒.set(文件名, Math.max(0, 毫秒));
      }
    }
  } else {
    统计.今日滚动日期 = 今天;
    统计.今日滚动毫秒 = 0;
  }
  for (const 文本状态 of Object.values(数据.文本状态)) {
    if (
      文本状态 &&
      typeof 文本状态.文件名 === 'string' &&
      typeof 文本状态.总滚动毫秒 === 'number' &&
      Number.isFinite(文本状态.总滚动毫秒)
    ) {
      统计.书籍滚动毫秒.set(文本状态.文件名, Math.max(0, 文本状态.总滚动毫秒));
    }
  }
}
