// 批量导入关键词的纯解析层：把弹窗文本框里的多行文本拆成待导入词，并把
// 「空行 / 本次重复 / 已存在」分开计数，让界面上报的几笔数互相对账：
//   总行数 = 待导入 + 已存在 + 本次重复 + 空行
// 不引用全局状态与 DOM，可单独测试（tests/batch-import-parse.test.mjs）。

// 行首行尾空白一律裁掉；零宽字符（ZWSP/ZWJ/LRM/RLM/BOM）粘贴时常见且肉眼不可见，
// 留在词内会匹配不上正文，一并裁掉。行内空格保留——正文里确有「蒋 介石」这类排版。
const 行首尾空白模式 = /^[\s\u200b-\u200f\ufeff]+|[\s\u200b-\u200f\ufeff]+$/gu;

// 结果行里「本书未出现」最多逐个列出的词数，超出只报总数。
const 未出现列举上限 = 8;

export function 清理关键词行(行文字) {
  return String(行文字 ?? '').replace(行首尾空白模式, '');
}

/* 解析多行输入。已存在集合为当前面板上非临时关键词的文本集合。 */
export function 解析批量关键词(文本, 已存在集合) {
  const 已有 =
    已存在集合 instanceof Set
      ? 已存在集合
      : new Set(Array.isArray(已存在集合) ? 已存在集合 : []);
  const 内容 = String(文本 ?? '');
  const 行列表 = 内容 === '' ? [] : 内容.split(/\r\n|\r|\n/);
  const 待导入列表 = [];
  const 本次已见 = new Set();
  let 空行数 = 0;
  let 重复行数 = 0;
  let 已存在数 = 0;

  for (const 原始行 of 行列表) {
    const 词 = 清理关键词行(原始行);
    if (!词) {
      空行数 += 1;
      continue;
    }
    if (本次已见.has(词)) {
      重复行数 += 1;
      continue;
    }
    本次已见.add(词);
    if (已有.has(词)) {
      已存在数 += 1;
      continue;
    }
    待导入列表.push(词);
  }

  return {
    总行数: 行列表.length,
    待导入列表,
    已存在数,
    重复行数,
    空行数,
  };
}

/* 输入框下方的实时计数行：0 的类别不写数字，只留实际发生的那几笔。 */
export function 描述批量解析(解析结果) {
  if (!解析结果.总行数) {
    return '';
  }
  const 片段 = [
    `共 ${解析结果.总行数} 行`,
    `待导入 ${解析结果.待导入列表.length}`,
  ];
  if (解析结果.已存在数) {
    片段.push(`已存在 ${解析结果.已存在数}`);
  }
  if (解析结果.重复行数) {
    片段.push(`本次重复 ${解析结果.重复行数}`);
  }
  if (解析结果.空行数) {
    片段.push(`空行 ${解析结果.空行数}`);
  }
  return 片段.join(' · ');
}

/* 导入后的结果行：待导入 = 已导入 + 本书未出现。 */
export function 描述批量导入结果(新增数, 未出现列表) {
  const 片段 = [];
  if (新增数) {
    片段.push(`已导入 ${新增数}`);
  }
  if (未出现列表.length) {
    const 列举 = 未出现列表
      .slice(0, 未出现列举上限)
      .map(function 加引号(词) {
        return `「${词}」`;
      })
      .join('、');
    const 省略 =
      未出现列表.length > 未出现列举上限 ? `… 共 ${未出现列表.length} 个` : '';
    片段.push(`本书未出现 ${未出现列表.length}：${列举}${省略}`);
  }
  return 片段.join(' · ');
}
