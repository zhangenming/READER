// 时段集合代数：纯计算、无 DOM、无模块状态。
// 记账层（js/滚动时段.js、js/可见时段.js）与展示层（js/阅读统计.js）共用这一套区间运算，
// 「几点到几点」和「读了多久」因此是同一份数据的两种看法，两张表不可能各算一套。
//
// 约定：段 = [起当日秒, 止当日秒]，止 > 起；「规范列表」= 已排序、互不重叠、互不相接。
// 记账层写入时只做无损合并（并掉重叠与首尾相接，间隙 0）——间隙一并就把发呆的时间
// 算进阅读时长，而时长现在是从这些段直接求和得来的。想看"连续的一段作息"，
// 请在展示层另用 按间隙合并 折算，别把它写回账上。

const 每日秒数 = 86_400;

// 过滤非法段并夹回当日范围内（旧数据每段可能多一位「种类」，一律只看前两位）。
function 取有效段(段列表) {
  const 结果 = [];
  for (const 段 of 段列表 ?? []) {
    if (!Array.isArray(段) || 段.length < 2) continue;
    const [原始起, 原始止] = 段;
    if (!Number.isFinite(原始起) || !Number.isFinite(原始止)) continue;
    const 起 = Math.max(0, Math.floor(原始起));
    const 止 = Math.min(每日秒数, Math.ceil(原始止));
    if (止 > 起) 结果.push([起, 止]);
  }
  return 结果;
}

// 并掉间隙不超过 间隙秒 的相邻段（重叠时间隙为负，同样命中）；间隙秒 = 0 即无损合并。
export function 按间隙合并(段列表, 间隙秒 = 0) {
  const 段们 = 取有效段(段列表).sort(
    (左, 右) => 左[0] - 右[0] || 左[1] - 右[1],
  );
  const 结果 = [];
  for (const 段 of 段们) {
    const 上一段 = 结果[结果.length - 1];
    if (上一段 && 段[0] - 上一段[1] <= 间隙秒) {
      上一段[1] = Math.max(上一段[1], 段[1]);
      continue;
    }
    结果.push(段);
  }
  return 结果;
}

// 规范列表：无损合并后的结果，写入账本用的就是这个形状。
export function 规范时段(段列表) {
  return 按间隙合并(段列表, 0);
}

// 多组时段并成一组（首尾相接也算一段）：总计 = 可见 ∪ 滚动。
// 复制一份再合并，绝不改动来路数组。
export function 合并时段(...段列表们) {
  return 规范时段(段列表们.flat());
}

// 差集：激活 = 可见 − 滚动（页面开着、但没在滚的那部分）。两侧都按规范列表处理。
export function 差集时段(被减列表, 减列表) {
  const 被减 = 规范时段(被减列表);
  const 减 = 规范时段(减列表);
  const 结果 = [];
  let 游标 = 0;
  for (const [起, 止] of 被减) {
    let 当前 = 起;
    while (游标 < 减.length && 减[游标][1] <= 当前) 游标 += 1;
    let idx = 游标;
    while (idx < 减.length && 减[idx][0] < 止) {
      const [减起, 减止] = 减[idx];
      if (减起 > 当前) 结果.push([当前, Math.min(减起, 止)]);
      当前 = Math.max(当前, 减止);
      if (当前 >= 止) break;
      idx += 1;
    }
    if (当前 < 止) 结果.push([当前, 止]);
  }
  return 结果;
}

// 一组段的总秒数（重叠段请先用 合并时段 并掉，否则会重复计时）。
export function 时段总秒(段列表) {
  return 取有效段(段列表).reduce((总数, 段) => 总数 + (段[1] - 段[0]), 0);
}
