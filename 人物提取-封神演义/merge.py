def fold(target, sources):
    t = by_name[target]
    for s in sources:
        g = by_name.pop(s, None)
        if g is None:
            print(f'  !! 被并组不存在: {s} -> {target}')
            continue
        for a, f in g['alias_freq'].items():
            t['alias_freq'][a] = t['alias_freq'].get(a, 0) + f
        for a in g['aliases']:
            if a != target:
                t['aliases'].add(a)
        t['chunks'] += g['chunks']
        t['n_chunks'] += g['n_chunks']
        t['nonhuman'] = t['nonhuman'] or g['nonhuman']
        t['mostly_mentioned_only'] = t['mostly_mentioned_only'] and g['mostly_mentioned_only']
        t['first_pct'] = min(t['first_pct'], g['first_pct'])
        if g['note'] and (not t['note'] or len(g['note']) > len(t['note'])):
            t['note'] = g['note']

